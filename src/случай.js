/**
 * Повторяемая случайность.
 *
 * Один и тот же посев даёт одну и ту же последовательность — на этом держится
 * вся генерация: карта, собранная по зерну 7, будет такой же и завтра, и на
 * другой машине. Со встроенным Math.random этап нельзя было бы ни повторить,
 * ни обсудить, ни починить.
 *
 * Внутри xorshift32 — три сдвига и три исключающих или. Он короткий, быстрый и
 * его хватает: нам нужна не криптография, а воспроизводимый шум.
 *
 * Раньше эта дюжина строк лежала в трёх файлах сразу — в генераторе, в
 * ландшафте и в фауне. Разошлись бы они хоть на единицу, и одинаковые зёрна
 * стали бы давать разные карты.
 */
export function случай(посев) {
  let x = (посев * 2654435761) >>> 0 || 1;
  return () => {
    x ^= x << 13;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    return x / 4294967296;
  };
}
