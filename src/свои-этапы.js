/**
 * Свои этапы: нарисованные в редакторе и загруженные в игру.
 *
 * Это инструмент разработки, такой же как линейка координат: в собранной игре
 * его нет вовсе. Весь модуль виден только из веток, закрытых проверкой
 * `import.meta.env.DEV`, — сборщик их выбрасывает, и вместе с ними уходит
 * отсюда всё до последней строчки.
 *
 * Хранятся этапы в браузере, рядом с прогрессом. Это значит: переживают
 * перезапуск игры и компьютера, но живут только в том браузере, где их
 * загрузили, и уходят вместе с очисткой данных сайта. Настоящий оригинал —
 * файл на диске, а не эта запись.
 *
 * В облако площадки они не идут нарочно: там место под прогресс игрока, и
 * карта в двадцать тысяч клеток его бы съела.
 */

const КЛЮЧ = 'capybara-свои-этапы';

/** Что должно быть в файле, чтобы этап можно было запустить. */
function разобрать(содержимое) {
  const данные = JSON.parse(содержимое);
  const карта = данные.карта;
  if (!Array.isArray(карта) || карта.length < 8) {
    throw new Error('в файле нет карты');
  }
  const строки = карта.map((с) => String(с));
  const всё = строки.join('');
  if (!всё.includes('P')) throw new Error('на карте нет старта «P»');
  if (!всё.includes('F')) throw new Error('на карте нет финиша «F»');

  const ширина = Math.max(...строки.map((с) => с.length));
  return {
    название: String(данные.название || 'Свой этап'),
    карта: строки.map((с) => с.padEnd(ширина, ' ')),
    // Параметры финиша этап несёт с собой: сколько он платит за звёзды, решает
    // сам. А параметры старта (уровень героя, покупки) не берём принципиально
    // — они для пробы в редакторе. Иначе карта распоряжалась бы тем, что
    // игрок заработал, и один и тот же этап у двоих был бы разной игрой.
    опытЗаЗвёзды: Array.isArray(данные.опытЗаЗвёзды) ? данные.опытЗаЗвёзды.map(Number) : null,
  };
}

/** Все загруженные этапы. */
export function свои() {
  try {
    const сырое = localStorage.getItem(КЛЮЧ);
    const список = сырое ? JSON.parse(сырое) : [];
    return Array.isArray(список) ? список : [];
  } catch {
    return [];
  }
}

function записать(список) {
  localStorage.setItem(КЛЮЧ, JSON.stringify(список));
}

/**
 * Добавить этап из файла. Если этап с таким названием уже есть, он
 * заменяется: правка карты не должна плодить одинаковые строчки в меню.
 *
 * @returns {object} добавленный этап
 * @throws если файл не похож на этап
 */
export function добавить(содержимое) {
  const этап = разобрать(содержимое);
  const список = свои().filter((э) => э.название !== этап.название);
  список.push({ ...этап, добавлен: Date.now() });
  записать(список);
  return этап;
}

export function убрать(название) {
  записать(свои().filter((э) => э.название !== название));
}
