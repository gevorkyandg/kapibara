/** Маршруты: пока один, из пяти этапов. */
export const ROUTES = [{ name: 'Долина', nameEn: 'The valley', levels: [0, 1, 2, 3, 4] }];

/** В каком маршруте лежит этап и какой он там по счёту. */
export function routeOf(levelIndex) {
  for (let r = 0; r < ROUTES.length; r++) {
    const i = ROUTES[r].levels.indexOf(levelIndex);
    if (i >= 0) return { route: r, stage: i };
  }
  return { route: 0, stage: levelIndex };
}

/**
 * Карта этапа.
 *
 * Зерно берём от номера этапа, чтобы карта каждый раз получалась одна и та
 * же: подсчёт монет идёт отдельным проходом, и «плавающая» карта разошлась бы
 * с рейтингом.
 */
export function buildLevelMap(levelIndex) {
  const level = LEVELS[levelIndex];
  if (!level) throw new Error(`Нет этапа с номером ${levelIndex}`);
  return generateStage({ seed: levelIndex + 1, ...level.generate });
}

/** Сколько монет на этапе. Нужно и для процента, и для цен в магазине. */
export function countCoins(levelIndex) {
  return buildLevelMap(levelIndex).reduce(
    (sum, row) => sum + [...row].filter((c) => c === 'o').length,
    0
  );
}
