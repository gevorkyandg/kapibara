/**
 * Уровни собираются из кусочков-картинок в символах.
 *
 * Каждый кусочек — 12 столбцов, а рядов столько, какой высоты этап. Ряд —
 * 60 px, поэтому 12 рядов это ровно экран (720 px), а 18 рядов — этап выше
 * экрана, по которому камера ездит и вверх-вниз. Все кусочки одного этапа
 * должны быть одной высоты, иначе карта не соберётся.
 *
 * Условные знаки:
 *   #  земля            =  платформа (парящая)
 *   o  монетка          *  место, где может появиться вкусняшка
 *   ^  шипы             ~  костёр (тоже нельзя трогать)
 *   m  черепашка        f  муха          l  лягушка
 *   e  ёжик (не топчется)  b  пчёлка
 *   d  дикобраз (стреляет иглами)   w  оса (пикирует)
 *   H  улей: одна метка — целый рой ос и табличка перед ним
 *   ?  случайный монстр (кто именно — решается при сборке этапа)
 *   j  жаба (язык)         z  змея в норе (не топчется)
 *   !  табличка-предупреждение перед длинной пропастью
 *   /  склон вверх    \\  склон вниз (в клетке 10 ступенек по 6 px)
 *   B  валун скатится по склону (две метки подряд — два валуна)
 *   v  шип с потолка пещеры    V  такой же, но падает точно под ноги
 *   s  пружина (прыжок вдвое выше)
 *   h  сердечко: возвращает потерянную жизнь
 *   c  облачко (прыжок на 20% выше, лопается)
 *   x  падающая платформа (дрогнет и рухнет)
 *   -  платформа, ездящая вбок    |  платформа, ездящая вверх-вниз
 *   P  старт капибары   F  финишный флаг
 *   (пробел) пусто. Дыра в земле — это пропасть, в неё можно упасть.
 *
 * Мерка проходимости: капибара первого уровня прыгает на 183 px вверх
 * (3 клетки) и перелетает 3 клетки по горизонтали — это проверено замерами
 * в игре. Отсюда и считается сложность пропасти.
 *
 * Но три клетки — это не потолок. Пропасть растёт с номером этапа, и на
 * поздних она заведомо шире базового прыжка: её берут поднятым уровнем героя
 * (каждый уровень прибавляет скорость и силу прыжка), двойным прыжком,
 * ускорением или их сочетанием. То есть покупки и уровень открывают путь, а
 * не только ускоряют игру.
 *
 * Островок — самостоятельный элемент, а не заплатка на широкой пропасти. Из
 * него собираются цепочки «пропасть — островок — пропасть», а на последних
 * этапах земли может не быть вовсе, и весь путь идёт по островкам.
 *
 * Что этап требует для прохождения — какой уровень героя, какие способности —
 * задаётся при генерации и показывается игроку как рекомендация, а не как
 * запрет.
 */

