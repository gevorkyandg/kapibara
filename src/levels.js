/**
 * Склеивает кусочки уровня в одну карту: массив из 12 строк во всю длину.
 * Заодно проверяет размеры кусочков — если карта поедет, лучше узнать об
 * этом сразу с понятным сообщением, а не ловить кривой уровень в игре.
 */
export function buildLevelMap(levelIndex) {
  const level = LEVELS[levelIndex];
  const first = CHUNKS[level.chunks[0]];
  if (!first) throw new Error(`Нет кусочка уровня: ${level.chunks[0]}`);

  // Высоту этапа задаёт его первый кусочек, остальные обязаны совпасть.
  const height = first.length;
  const rows = new Array(height).fill('');

  for (const name of level.chunks) {
    const chunk = CHUNKS[name];
    if (!chunk) throw new Error(`Нет кусочка уровня: ${name}`);
    if (chunk.length !== height) {
      throw new Error(
        `Кусочек ${name}: ${chunk.length} рядов, а этап «${level.name}» высотой ${height}`
      );
    }
    chunk.forEach((line, r) => {
      if (line.length !== CHUNK_W) {
        throw new Error(`Кусочек ${name}, ряд ${r}: ${line.length} символов вместо ${CHUNK_W}`);
      }
      rows[r] += line;
    });
  }

  return rows;
}

/** Сколько монет на уровне. Нужно и для процента, и для цен в магазине. */
export function countCoins(levelIndex) {
  return buildLevelMap(levelIndex).reduce(
    (sum, row) => sum + [...row].filter((c) => c === 'o').length,
    0
  );
}
