/**
 * Маршруты и этапы.
 *
 * Этапы больше не рисуются символами вручную — они описываются участками, а
 * карту из описания собирает generate.js. Описание читается сверху вниз как
 * маршрут: «равнина с черепашкой, пропасть в три клетки, пещера с шипами,
 * горка с валуном». Длина, число монет и сладостей заданы числами, остальное
 * генератор разводит сам.
 *
 * Условные знаки готовой карты (их же кладёт генератор):
 *   #  земля            =  площадка (парящая)
 *   o  монетка          *  сладость
 *   ^  колючки          ~  костёр
 *   m  черепашка        f  муха          l  лягушка
 *   e  ёжик             b  пчёлка
 *   d  дикобраз         w  оса           H  улей (рой ос с табличкой)
 *   j  жаба             z  змея          p  панголин
 *   /  склон вверх    \\  склон вниз
 *   B  метка валуна (сколько подряд, столько валунов в заходе)
 *   v  шип с потолка    V  шип, метящий точно под ноги
 *   s  пружина          c  облачко
 *   x  падающая площадка
 *   -  площадка, ездящая вбок    |  площадка, ездящая вверх-вниз
 *   h  сердечко         !  табличка-предупреждение
 *   P  старт            F  финишная черта
 *
 * Мерка проходимости замерена в игре на капибаре 1-го уровня: прыжок
 * поднимает на 176 px и переносит через 220 px пустоты вровень, 196 px с
 * подъёмом на клетку, 172 px с подъёмом на две. Заряженная пружина
 * подбрасывает на 340 px. Отсюда и берутся ширины пропастей.
 *
 * Пропасть — самостоятельное препятствие, и её ширина растёт от этапа к
 * этапу. Островок — тоже самостоятельный элемент, а не заплатка на широкой
 * пропасти: из них собираются сплошные пропасти, где земли нет вовсе.
 *
 * Что этап требует для прохождения, задаётся полем «нужно» и показывается
 * игроку как рекомендация, а не как запрет.
 */

