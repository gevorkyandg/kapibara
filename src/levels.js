/** Маршруты: пока один, из пяти этапов. */
/**
 * Этапы, загруженные из редактора.
 *
 * Только в разработке: в собранной игре этой ветки нет, и вместе с ней уходит
 * весь модуль своих этапов. Игроку они и не нужны — до него доезжает готовое,
 * уже вписанное в кампанию.
 */
export const LEVELS = [...КАМПАНИЯ];

export const ROUTES = [{ name: 'Долина', nameEn: 'The valley', levels: [0, 1, 2, 3, 4] }];

// Ветка целиком выпадает из сборки вместе с проверкой: в игре, которая уедет
// к игрокам, нет ни своих этапов, ни маршрута под них, ни даже этих строк.
if (import.meta.env.DEV) {
  const СВОИ = свои();
  if (СВОИ.length) {
    const первый = LEVELS.length;
    for (const э of СВОИ) {
      LEVELS.push({
        name: э.название,
        nameEn: э.название,
        theme: 0,
        свой: true,
        нужно: 'Загружен из редактора.',
        карта: э.карта,
        опытЗаЗвёзды: э.опытЗаЗвёзды,
        детали: э.детали ?? {},
        правила: э.правила ?? {},
      });
    }
    ROUTES.push({
      name: 'Мои этапы',
      nameEn: 'My stages',
      свой: true,
      levels: СВОИ.map((_, i) => первый + i),
    });
  }
}

/** В каком маршруте лежит этап и какой он там по счёту. */
export function routeOf(levelIndex) {
  for (let r = 0; r < ROUTES.length; r++) {
    const i = ROUTES[r].levels.indexOf(levelIndex);
    if (i >= 0) return { route: r, stage: i };
  }
  return { route: 0, stage: levelIndex };
}

/**
 * Карта этапа.
 *
 * Зерно берём от номера этапа, чтобы карта каждый раз получалась одна и та
 * же: подсчёт монет идёт отдельным проходом, и «плавающая» карта разошлась бы
 * с рейтингом.
 */
export function buildLevelMap(levelIndex) {
  const level = LEVELS[levelIndex];
  if (!level) throw new Error(`Нет этапа с номером ${levelIndex}`);

  // Проба из редактора идёт первой и только в разработке: в собранной игре
  // этой ветки нет вовсе, чтобы чужой localStorage не мог подменить этап.
  const проба = пробаИзРедактора(levelIndex);
  if (проба) return проба.строки;

  // Нарисованный этап несёт карту с собой. Правила генератора — монеты не у
  // костра, монстры не у старта, сердечко после трудного места — на неё не
  // распространяются: за них отвечает тот, кто рисовал.
  if (level.карта) return level.карта.slice();

  return generateStage({ seed: levelIndex + 1, ...level.generate });
}

/** Этап, нарисованный в редакторе и отправленный в игру на пробу. */
function пробаИзРедактора(levelIndex) {
  if (!import.meta.env.DEV) return null;
  try {
    const сырое = localStorage.getItem('capybara-редактор-карта');
    if (!сырое) return null;
    const проба = JSON.parse(сырое);
    if (проба.этап !== levelIndex) return null;
    if (!Array.isArray(проба.строки) || !проба.строки.length) return null;
    return проба;
  } catch {
    return null;
  }
}

/**
 * Подробности этапа: сдвиги предметов внутри клеток и размах хода платформ.
 *
 * Карта из символов такого сказать не может — в клетке помещается один знак и
 * ни числа рядом с ним. Поэтому подробности идут отдельной таблицей, и есть
 * они только у рисованных этапов: у сгенерированных всё стоит ровно по
 * клеткам, а платформы ходят стандартным патрулём.
 */
export function деталиЭтапа(levelIndex) {
  const проба = пробаИзРедактора(levelIndex);
  if (проба?.детали) return проба.детали;
  return LEVELS[levelIndex]?.детали ?? {};
}

/**
 * Особые правила этапа.
 *
 * Сейчас правило одно: засчитывать ли финиш по высоте. На обычном этапе черта
 * пересекается по любой высоте — так и задумано. Но в лабиринте дорога
 * возвращается назад по другому этажу, и колонку с флажком игрок проходит на
 * каждом из них; без оглядки на высоту этап заканчивался бы на первом же.
 */
export function правилаЭтапа(levelIndex) {
  const проба = пробаИзРедактора(levelIndex);
  if (проба?.правила) return проба.правила;
  return LEVELS[levelIndex]?.правила ?? {};
}

/** Сколько монет на этапе. Нужно и для процента, и для цен в магазине. */
export function countCoins(levelIndex) {
  return buildLevelMap(levelIndex).reduce(
    (sum, row) => sum + [...row].filter((c) => c === 'o').length,
    0
  );
}
