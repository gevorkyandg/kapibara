/**
 * Расселение фауны по готовому рельефу.
 *
 * Второй шаг генерации: дорога уже утверждена, теперь на неё селят монстров и
 * раскладывают монеты со сладостями. Разделение нарочное — рельеф и население
 * переделываются по отдельности, и удачную дорогу не приходится терять из-за
 * неудачно вставшего ёжика.
 *
 * Правила расстановки взяты не с потолка, а из замеров и статистики живых
 * игроков: пятачок у старта пуст, у пружины монстров нет, монета у огня не
 * ниже третьей клетки и таких монет на этап не больше трёх.
 */

const КЛЕТКА = 60;
const ЧИСТО_У_СТАРТА = 400; // px: черепаха у точки возрождения — это петля смертей
const ЧИСТО_У_ФИНИША = 8; // клеток: у флажка этап уже решён
const МЕЖДУ_МОНСТРАМИ = 3; // клеток, если это не задуманная связка
const У_ПРУЖИНЫ = 3; // клеток: на пружину надо прыгать, а не уворачиваться
const НАД_ОПАСНЫМ_МАКС = 3; // столько монет на этап можно повесить над огнём

/** Кто появляется на какой сложности. Список накопительный. */
const ЗВЕРИ = {
  1: ['m', 'f'],
  2: ['m', 'f', 'l', 'e'],
  3: ['m', 'f', 'l', 'e', 'b', 'd'],
  4: ['m', 'f', 'l', 'e', 'b', 'd', 'w', 'j', 'p'],
  5: ['m', 'f', 'l', 'e', 'b', 'd', 'w', 'j', 'p', 'z', 'H'],
};

/** Летающие живут в воздухе, а не на земле. */
const ЛЕТАЮЩИЕ = new Set(['f', 'b', 'w', 'H']);

const ТВЁРДО = new Set(['#', '=', '/', '\\']);
const ФАУНА = new Set(['m', 'f', 'l', 'e', 'b', 'd', 'w', 'j', 'z', 'p', 'H', 'o', '*', 'h']);

function случай(seed) {
  let x = (seed * 2654435761) >>> 0 || 1;
  return () => {
    x ^= x << 13;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    return x / 4294967296;
  };
}

/**
 * Полки колонки: ряды, на которых можно стоять.
 *
 * На лабиринте их несколько — по одной на этаж, — и населять нужно все:
 * игрок пройдёт по каждой. Полкой считается твёрдая клетка, над которой есть
 * место для зверя.
 */
function полки(сетка, col) {
  const найдено = [];
  for (let row = 1; row < сетка.length; row++) {
    if (!ТВЁРДО.has(сетка[row][col])) continue;
    if (сетка[row - 1][col] !== ' ') continue;
    найдено.push(row);
  }
  return найдено;
}

function рядом(сетка, col, row, знаки, вширь = 1, ввысь = 1) {
  for (let d = -вширь; d <= вширь; d++) {
    for (let v = -ввысь; v <= ввысь; v++) {
      const c = сетка[row + v]?.[col + d];
      if (c && знаки.has(c)) return true;
    }
  }
  return false;
}

/**
 * Стоит ли колонка на самой кромке.
 *
 * Монстр у края пропасти запирает переправу: игроку негде разбежаться и некуда
 * приземлиться. Но требовать твёрдого с обеих сторон нельзя — на узких
 * карнизах лабиринта тогда не поселится никто. Хватит одной твёрдой соседки.
 */
function уОбрыва(сетка, col, row) {
  let опор = 0;
  for (const d of [-1, 1]) {
    const сосед = сетка[row]?.[col + d];
    if (сосед !== undefined && ТВЁРДО.has(сосед)) опор++;
  }
  return опор === 0;
}

/**
 * Расселить фауну по карте.
 *
 * Прежнее население стирается: перегенерация должна давать новую расстановку,
 * а не подсыпать зверей к старым.
 *
 * @param {string[]} карта строки рельефа
 * @returns {string[]} новые строки
 */
export function расставитьФауну(
  карта,
  { сложность = 1, зерно = 1, монет = 30, сладостей = 3, сердечек = 0 } = {}
) {
  const rnd = случай(Number(зерно) || 1);
  const сетка = карта.map((строка) => [...строка].map((з) => (ФАУНА.has(з) ? ' ' : з)));
  const колонок = сетка[0].length;

  let стартCol = 0;
  let финишCol = колонок - 1;
  for (let col = 0; col < колонок; col++) {
    for (let row = 0; row < сетка.length; row++) {
      if (сетка[row][col] === 'P') стартCol = col;
      if (сетка[row][col] === 'F') финишCol = col;
    }
  }
  const чистоУСтарта = Math.ceil(ЧИСТО_У_СТАРТА / КЛЕТКА);

  /** Можно ли вообще что-то ставить в эту колонку. */
  const свободна = (col) =>
    Math.abs(col - стартCol) > чистоУСтарта && Math.abs(col - финишCol) > ЧИСТО_У_ФИНИША;

  // ── Монстры ────────────────────────────────────────────────────────────
  const порода = ЗВЕРИ[сложность] ?? ЗВЕРИ[1];
  // Чем выше сложность, тем гуще населено и тем чаще звери ходят связками.
  const плотность = 0.08 + сложность * 0.06;
  const связкой = сложность >= 3 ? (сложность - 2) * 0.2 : 0;
  const поставленные = [];

  const местоГодится = (col, row) => {
    if (!свободна(col)) return false;
    if (сетка[row - 1][col] !== ' ') return false;
    if (рядом(сетка, col, row, new Set(['s']), У_ПРУЖИНЫ, 2)) return false;
    if (рядом(сетка, col, row, new Set(['/', '\\']), 1, 1)) return false;
    return true;
  };

  const поселить = (col, row, кто) => {
    const летит = ЛЕТАЮЩИЕ.has(кто);
    const ряд = летит ? Math.max(1, row - 3) : row - 1;
    if (сетка[ряд][col] !== ' ') return false;
    сетка[ряд][col] = кто;
    поставленные.push({ col, row: ряд, кто });
    return true;
  };

  for (let col = 2; col < колонок - 2; col++) {
    if (rnd() > плотность) continue;
    const где = полки(сетка, col);
    if (!где.length) continue;
    const row = где[Math.floor(rnd() * где.length)];
    if (!местоГодится(col, row)) continue;
    if (уОбрыва(сетка, col, row)) continue;
    if (поставленные.some((м) => Math.abs(м.col - col) < МЕЖДУ_МОНСТРАМИ)) continue;

    const кто = порода[Math.floor(rnd() * порода.length)];
    if (!поселить(col, row, кто)) continue;

    // Связка: второй зверь рядом, чтобы место решалось не одним прыжком.
    if (rnd() < связкой) {
      const сосед = col + между(2, 3);
      const рядомПолки = полки(сетка, сосед);
      if (рядомПолки.length && местоГодится(сосед, рядомПолки[0])) {
        поселить(сосед, рядомПолки[0], порода[Math.floor(rnd() * порода.length)]);
      }
    }
  }

  function между(от, до) {
    return от + Math.floor(rnd() * (до - от + 1));
  }

  // ── Монеты ─────────────────────────────────────────────────────────────
  //
  // Порядок такой: сперва монеты у монстров — каждый сторожит свою, кроме
  // дикобраза, к которому не подойти; потом дуги над пропастями; остальное
  // раскладывается вдоль дороги.
  let осталось = Number(монет) || 0;
  let надОпасным = 0;

  /** Ближайшая земля под клеткой — от неё и считается высота монеты. */
  const землиПод = (col, row) => {
    for (let r = row + 1; r < сетка.length; r++) {
      if (ТВЁРДО.has(сетка[r][col])) return r;
    }
    return сетка.length;
  };

  const положитьМонету = (col, row) => {
    if (осталось <= 0) return false;
    if (!сетка[row] || сетка[row][col] !== ' ') return false;
    if (!свободна(col)) return false;

    const пол = землиПод(col, row);
    const высота = пол < сетка.length ? пол - row : 0;
    // Выше четвёртой клетки монету не достать: прыжок поднимает на 176 px.
    if (высота > 4) return false;
    // Рядом с огнём и колючками монета висит не ниже третьей клетки: ниже её
    // не взять, не пройдя ногами сквозь пламя. И таких на этап не больше трёх.
    const опасноРядом = рядом(сетка, col, row, new Set(['^', '~']), 1, 2);
    if (опасноРядом) {
      if (высота < 3) return false;
      if (надОпасным >= НАД_ОПАСНЫМ_МАКС) return false;
      надОпасным++;
    }
    сетка[row][col] = 'o';
    осталось--;
    return true;
  };

  for (const м of поставленные) {
    if (м.кто === 'd') continue; // дикобраз бьёт иглами во все стороны
    положитьМонету(м.col, м.row - 2);
  }

  // Дуги над пропастями: три монеты по следу прыжка.
  for (let col = 2; col < колонок - 3 && осталось > 0; col++) {
    const слева = полки(сетка, col);
    const справа = полки(сетка, col + 1);
    if (!слева.length || справа.length) continue;
    const ряд = слева[слева.length - 1];
    let ширина = 1;
    while (ширина < 8 && !полки(сетка, col + 1 + ширина).length) ширина++;
    if (ширина < 2) continue;
    const середина = col + Math.round(ширина / 2);
    положитьМонету(середина, ряд - 3);
    положитьМонету(середина - 1, ряд - 2);
    положитьМонету(середина + 1, ряд - 2);
    col += ширина;
  }

  // Остальное — цепочками вдоль дороги, по две-три монеты подряд.
  let попыток = колонок * 3;
  while (осталось > 0 && попыток-- > 0) {
    const col = между(2, колонок - 3);
    const где = полки(сетка, col);
    if (!где.length) continue;
    const ряд = где[Math.floor(rnd() * где.length)];
    const высота = между(1, 3);
    const длина = между(2, 3);
    for (let i = 0; i < длина; i++) положитьМонету(col + i, ряд - высота);
  }

  // ── Сладости и сердечки ────────────────────────────────────────────────
  let сладких = Number(сладостей) || 0;
  попыток = колонок * 2;
  while (сладких > 0 && попыток-- > 0) {
    const col = между(4, колонок - 5);
    const где = полки(сетка, col);
    if (!где.length) continue;
    const ряд = где[Math.floor(rnd() * где.length)] - между(1, 3);
    if (!сетка[ряд] || сетка[ряд][col] !== ' ' || !свободна(col)) continue;
    сетка[ряд][col] = '*';
    сладких--;
  }

  // Сердечко ставится после самого трудного места: улья, дикобраза или
  // тройки валунов. Это награда за пройденное, а не находка перед началом.
  let сердец = Number(сердечек) || 0;
  if (сердец > 0) {
    let рубеж = -1;
    for (let col = 0; col < колонок; col++) {
      for (let row = 0; row < сетка.length; row++) {
        const з = сетка[row][col];
        if (з === 'H' || з === 'd' || з === 'B') рубеж = Math.max(рубеж, col);
      }
    }
    if (рубеж < 0) рубеж = Math.floor(колонок / 2);
    for (let col = рубеж + 3; col < колонок - 3 && сердец > 0; col++) {
      const где = полки(сетка, col);
      if (!где.length) continue;
      const ряд = где[0] - 2;
      if (!сетка[ряд] || сетка[ряд][col] !== ' ' || !свободна(col)) continue;
      сетка[ряд][col] = 'h';
      сердец--;
    }
  }

  return сетка.map((ряд) => ряд.join(''));
}

/** Сколько на карте монет — редактор показывает это рядом со схемой. */
export function сосчитатьМонеты(карта) {
  return карта.reduce((сумма, ряд) => сумма + [...ряд].filter((з) => з === 'o').length, 0);
}
