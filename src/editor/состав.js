/**
 * Состав этапа → описание участков для генератора.
 *
 * Генератор умеет читать только упорядоченный список участков: «равнина с
 * черепашкой, пропасть в две клетки, пещера с шипами». Человеку же удобнее
 * задавать состав: длину, сложность и сколько кого поставить. Этот файл —
 * переводчик между тем и другим.
 *
 * Он нарочно не решает за генератор ничего из того, что тот умеет сам:
 * промежутки, монеты, сладости, разведение летающих и чистка пятачка у
 * старта остаются на его стороне. Здесь только порядок препятствий и то, на
 * какой равнине кто стоит.
 */

/** Тот же генератор случайностей, что и в generate.js: xorshift от зерна. */
function случай(seed) {
  let x = (seed * 2654435761) >>> 0 || 1;
  return () => {
    x ^= x << 13;
    x ^= x >>> 17;
    x ^= x << 5;
    x >>>= 0;
    return x / 4294967296;
  };
}

/** Состав по умолчанию — с него открывается панель генерации. */
export const ПО_УМОЛЧАНИЮ = {
  название: 'Новый этап',
  длина: 1,
  сложность: 1,
  монет: 30,
  сладостей: 2,
  сердечко: false,
  зерно: 1,
  монстры: { m: 2, f: 1, l: 1, e: 0, b: 0, d: 0, w: 0, H: 0, j: 0, z: 0, p: 0 },
  опасности: { '^': 2, '~': 1 },
  пропастей: 6,
  горок: 1,
  пещер: 0,
  гор: 0,
  пружин: 0,
  островков: 0,
  сплошных: 0,
};

/**
 * Просвет между полосами опасностей — сколько клеток чистой земли остаётся
 * между колючками. Чем выше сложность, тем уже окно для приземления.
 */
const ПРОСВЕТ = [3, 2, 2, 1, 1];

/**
 * Ширина пропасти растёт и со сложностью, и по ходу этапа: первая пропасть
 * всегда посильнее последней. Предел — четыре клетки: это уже за пределом
 * базового прыжка, и такую берут двойным прыжком или разгоном.
 */
function ширинаПропасти(сложность, доля) {
  const предел = Math.min(4, 1 + Math.ceil(сложность * 0.7));
  return Math.max(1, Math.round(1 + доля * (предел - 1)));
}

function перемешать(список, rnd) {
  for (let i = список.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [список[i], список[j]] = [список[j], список[i]];
  }
  return список;
}

/**
 * Собрать описание этапа из состава.
 *
 * @param {object} состав поля из ПО_УМОЛЧАНИЮ
 * @returns {object} spec для generateStage
 */
export function спецИзСостава(состав) {
  const s = { ...ПО_УМОЛЧАНИЮ, ...состав };
  const rnd = случай(Number(s.зерно) || 1);

  // ── Что должно встретиться по дороге ──────────────────────────────────
  const события = [];
  const добавить = (сколько, тип) => {
    for (let i = 0; i < (Number(сколько) || 0); i++) события.push({ тип });
  };
  добавить(s.пропастей, 'пропасть');
  добавить(s.горок, 'горка');
  добавить(s.пещер, 'пещера');
  добавить(s.островков, 'островок');
  добавить(s.сплошных, 'сплошная');
  добавить(s.пружин, 'пружина');
  for (const [знак, сколько] of Object.entries(s.опасности ?? {})) {
    for (let i = 0; i < (Number(сколько) || 0); i++) события.push({ тип: 'полоса', знак });
  }
  перемешать(события, rnd);

  // Гора — всегда ближе к концу: она отвесная, берётся пружиной, и дальше
  // дорога идёт поверху. Поставить её в начале значит запереть весь этап.
  for (let i = 0; i < (Number(s.гор) || 0); i++) события.push({ тип: 'гора' });

  // ── Кто на этих равнинах живёт ────────────────────────────────────────
  const мешок = [];
  for (const [буква, сколько] of Object.entries(s.монстры ?? {})) {
    for (let i = 0; i < (Number(сколько) || 0); i++) мешок.push(буква);
  }
  перемешать(мешок, rnd);

  const участки = [];
  const равнина = (пусто = false) => {
    const монстры = [];
    if (!пусто && мешок.length) монстры.push(мешок.pop());
    // Иногда двое на одной равнине — иначе этап читается как метроном.
    if (!пусто && мешок.length && rnd() < 0.3) монстры.push(мешок.pop());
    участки.push({
      вид: 'равнина',
      клеток: 5 + Math.floor(rnd() * 3),
      ...(монстры.length ? { монстры } : {}),
    });
  };

  // Первая равнина всегда пустая: у старта монстров всё равно не будет —
  // генератор чистит пятачок, — и занимать ими место незачем.
  равнина(true);

  события.forEach((с, i) => {
    const доля = события.length > 1 ? i / (события.length - 1) : 1;
    switch (с.тип) {
      case 'пропасть':
        участки.push({ вид: 'пропасть', ширина: ширинаПропасти(s.сложность, доля) });
        break;
      case 'полоса':
        участки.push({
          вид: 'равнина',
          клеток: 8,
          полосы: [[с.знак, с.знак]],
          просвет: ПРОСВЕТ[s.сложность - 1] ?? 2,
        });
        break;
      case 'горка':
        участки.push({
          вид: 'горка',
          вверх: 2 + Math.floor(rnd() * 2),
          валунов: Math.min(3, 1 + Math.floor(s.сложность / 2)),
        });
        // После подъёма нужна дорога вниз, иначе этап уходит в потолок.
        участки.push({ вид: 'ступень', вниз: 1, клеток: 4 });
        break;
      case 'пещера':
        участки.push({ вид: 'пещера', клеток: 10, шипов: 1 + Math.floor(s.сложность / 2) });
        break;
      case 'островок':
        участки.push({ вид: 'пропасть', ширина: 2 });
        участки.push({ вид: 'островок', ширина: 2 });
        break;
      case 'сплошная':
        участки.push({
          вид: 'сплошная',
          звенья: [
            { пропасть: 3 },
            { вид: rnd() < 0.5 ? 'движущаяся' : 'облачко' },
            { пропасть: 3 },
          ],
        });
        break;
      case 'пружина':
        участки.push({ вид: 'пружина', монет: 3 });
        break;
      case 'гора':
        участки.push({ вид: 'гора', высота: 3 + Math.floor(s.сложность / 2), разбег: 4 });
        break;
      default:
        break;
    }
    равнина();
  });

  // Кого не расставили — тем добавляем равнин: заказ на монстров важнее
  // круглой длины, а длину генератор всё равно доберёт промежутками.
  while (мешок.length) равнина();

  return {
    длина: Number(s.длина) || 1,
    сложность: Number(s.сложность) || 1,
    монет: Number(s.монет) || 0,
    сладостей: Number(s.сладостей) || 0,
    ...(s.сердечко ? { сердечко: true } : {}),
    участки,
  };
}
