/**
 * Генератор рельефа для редактора.
 *
 * Старый генератор собирал этап из готовых участков и всегда одной высоты —
 * четырнадцать рядов, один пол. Этот делает другое: берёт заданный размер
 * карты и сложность и строит из них дорогу, которая на низких сложностях
 * стелется прямой, а на высоких заворачивается лабиринтом в несколько этажей.
 *
 * Фауны здесь нет вовсе. Сперва утверждается дорога, потом на неё селят
 * монстров и раскладывают монеты — этим занимается «фауна.js».
 *
 * Мерки взяты из игры и замерены на капибаре первого уровня:
 *   прыжок  — 176 px вверх, 220 px вбок вровень (это три клетки с хвостиком);
 *   пружина — 340 px вверх с нажатием, до 310 px вперёд;
 *   облачко — 148 px вверх, до 200 px вперёд;
 *   падение — смертельно с 760 px, то есть с двенадцати клеток.
 */

import { случай } from '../случай.js';
import { проверитьПроходимость } from '../generate.js';

const КЛЕТКА = 60;

/** Ширина пропастей и их частота по сложности. */
const ПРОПАСТИ = {
  1: { мин: 1, макс: 2, доля: 0.22, помощь: 0 },
  2: { мин: 2, макс: 3, доля: 0.3, помощь: 0.35 },
  3: { мин: 3, макс: 5, доля: 0.36, помощь: 0.7 },
  4: { мин: 3, макс: 6, доля: 0.4, помощь: 0.8 },
  5: { мин: 3, макс: 7, доля: 0.45, помощь: 0.9 },
};

/** Как часто на ровном месте встречается опасность и как охотно они парами. */
const ОПАСНОСТИ = {
  1: { доля: 0.1, парами: 0 },
  2: { доля: 0.16, парами: 0.2 },
  3: { доля: 0.22, парами: 0.4 },
  4: { доля: 0.26, парами: 0.6 },
  5: { доля: 0.3, парами: 0.75 },
};

/** Сколько этажей у дороги: с четвёртой сложности она заворачивается вверх. */
const ЭТАЖЕЙ = { 1: 1, 2: 1, 3: 1, 4: 2, 5: 3 };

/** Между этажами пять клеток: пружина добирает их с запасом, падение — нет. */
const МЕЖДУ_ЭТАЖАМИ = 5;

const между = (rnd, от, до) => от + Math.floor(rnd() * (до - от + 1));

/** Пустая карта: массив массивов символов, потом склеим в строки. */
function холст(колонок, рядов) {
  return new Array(рядов).fill(null).map(() => new Array(колонок).fill(' '));
}

function поставить(карта, col, row, знак) {
  if (row < 0 || row >= карта.length) return;
  if (col < 0 || col >= карта[0].length) return;
  карта[row][col] = знак;
}

/**
 * Земля этажа.
 *
 * Нижний этаж — сплошная толща до низа карты: по нему и ходят, и он же
 * держит вид. Верхние — полоса в одну клетку: это карниз, под ним должно
 * быть видно небо, иначе лабиринт превращается в слоёный пирог.
 */
function земля(карта, col, ряд, нижний) {
  if (нижний) {
    for (let r = ряд; r < карта.length; r++) поставить(карта, col, r, '#');
  } else {
    поставить(карта, col, ряд, '#');
  }
}

/**
 * Чем перебираться через пропасть, которую не взять прыжком.
 *
 * Островок — самостоятельный элемент, а не заплатка: из него собираются
 * цепочки. Дальше по сложности идут те, что требуют расчёта, — падающая
 * площадка, движущаяся, облачко. Пружину ставим на край перед самой широкой
 * пропастью: она единственная перекидывает через семь клеток.
 */
function перебраться(карта, от, до, ряд, нижний, сложность, rnd) {
  const ширина = до - от + 1;
  const середина = Math.floor((от + до) / 2);
  const выбор = rnd();

  if (ширина >= 6) {
    // Через такую пропасть перекинет только пружина: ставим её на кромке.
    поставить(карта, от - 1, ряд - 1, 's');
    return;
  }

  if (выбор < 0.4 || сложность <= 2) {
    // Островок: клетка земли посреди пустоты.
    земля(карта, середина, ряд, false);
    if (ширина >= 5) земля(карта, середина + 1, ряд, false);
    return;
  }
  if (выбор < 0.6) {
    поставить(карта, середина, ряд - 1, 'x'); // падающая площадка
    return;
  }
  if (выбор < 0.8) {
    поставить(карта, середина, ряд - 1, '-'); // движущаяся вбок
    return;
  }
  // Облачко: подбрасывает ниже прыжка и лопается, поэтому ставим пару.
  поставить(карта, середина - 1, ряд - 2, 'c');
  поставить(карта, середина + 1, ряд - 2, 'c');
}

/** Полоса колючек или костров на ровном месте. */
function опасность(карта, col, ряд, сложность, rnd) {
  const о = ОПАСНОСТИ[сложность];
  const знак = rnd() < 0.6 ? '^' : '~';
  поставить(карта, col, ряд - 1, знак);
  // Две подряд — это уже прыжок с расчётом, а не шаг в сторону.
  if (знак === '^' && rnd() < о.парами) поставить(карта, col + 1, ряд - 1, '^');
}

/**
 * Горка с валунами: подъём, площадка наверху и спуск.
 *
 * Живёт только на нижнем этаже — ей нужна толща под собой, иначе склон
 * повиснет в воздухе. Возвращает, сколько клеток заняла.
 */
function горка(карта, col, ряд, сложность, rnd) {
  const высота = между(rnd, 2, сложность >= 4 ? 4 : 3);
  const площадка = между(rnd, 3, 6);
  let x = col;

  for (let i = 0; i < высота; i++) {
    const верх = ряд - i;
    земля(карта, x, верх, true);
    поставить(карта, x, верх - 1, '/');
    x++;
  }
  const верх = ряд - высота;
  for (let i = 0; i < площадка; i++) {
    земля(карта, x, верх, true);
    x++;
  }
  // Валуны скатываются навстречу: их метки стоят на площадке.
  const валунов = Math.min(3, Math.max(1, сложность - 1));
  for (let i = 0; i < валунов; i++) поставить(карта, x - 1 - i, верх - 1, 'B');

  for (let i = высота - 1; i >= 0; i--) {
    const низ = ряд - i;
    земля(карта, x, низ, true);
    поставить(карта, x, низ - 1, '\\');
    x++;
  }
  return x - col;
}

/**
 * Один этаж дороги — от левого края до правого.
 *
 * Идём слева направо и выкладываем: ровное место, иногда пропасть, иногда
 * опасность, иногда горку. Чем выше сложность, тем чаще и шире.
 */
function этаж(карта, { от, до, ряд, нижний, сложность, rnd }) {
  const п = ПРОПАСТИ[сложность];
  const о = ОПАСНОСТИ[сложность];
  let x = от;
  // Начало этажа всегда твёрдое: на кромку игрок приходит с перехода.
  const запас = 3;
  // Сколько твёрдого нужно положить, прежде чем разрывать дорогу снова.
  // Без этого две пропасти подряд сливаются в одну, которую уже ничем не
  // перейти: разбежаться негде, приземляться некуда.
  let разбег = запас;

  while (x <= до) {
    const осталось = до - x;
    const можноПропасть =
      разбег <= 0 && x > от + запас && осталось > п.макс + запас && rnd() < п.доля;

    if (можноПропасть) {
      let ширина = между(rnd, п.мин, Math.min(п.макс, осталось - запас));
      const помощь = ширина > 3 && rnd() < п.помощь;
      // Без подмоги пропасть не шире трёх клеток: базовый прыжок берёт 220 px,
      // то есть три клетки с небольшим хвостиком.
      if (!помощь) ширина = Math.min(ширина, 3);
      if (помощь) перебраться(карта, x, x + ширина - 1, ряд, нижний, сложность, rnd);
      x += ширина;
      разбег = между(rnd, 4, 8);
      continue;
    }
    разбег--;

    if (нижний && сложность >= 3 && осталось > 14 && rnd() < 0.14) {
      x += горка(карта, x, ряд, сложность, rnd);
      continue;
    }

    земля(карта, x, ряд, нижний);
    if (x > от + запас && осталось > запас && rnd() < о.доля) {
      опасность(карта, x, ряд, сложность, rnd);
    }
    x++;
  }
}

/**
 * Переход между этажами.
 *
 * Наверх ведёт пружина: она даёт 340 px, то есть пять клеток с запасом, и в
 * отличие от цепочки облачков не может кончиться. На пятой сложности к ней
 * добавляются облачка и движущаяся площадка — чтобы подъёмы не были на одно
 * лицо.
 */
function переход(карта, { x, снизу, сверху, сложность, rnd }) {
  const способ = сложность >= 5 ? между(rnd, 0, 2) : 0;

  if (способ === 0) {
    поставить(карта, x, снизу - 1, 's');
    return;
  }
  if (способ === 1) {
    // Лесенка облачков: каждое подбрасывает на 148 px — чуть больше двух
    // клеток, поэтому ставим их через две.
    for (let r = снизу - 2; r > сверху; r -= 2) поставить(карта, x, r, 'c');
    return;
  }
  поставить(карта, x, Math.floor((снизу + сверху) / 2), '|');
}

/**
 * Заделать непроходимые разрывы.
 *
 * Генератор кладёт дорогу вслепую, и как ни считай ширину, где-нибудь да
 * сойдутся край горки и край пропасти так, что прыжка не хватит. Спорить с
 * этим бесполезно — проще пройтись той же мерой, что и проверка в редакторе,
 * и в каждый слишком широкий разрыв уронить островок.
 *
 * Меряем и чиним по кругу: один островок иногда рождает два разрыва поуже,
 * их тоже нужно осмотреть.
 */
function починить(строки) {
  let сетка = строки.map((с) => [...с]);

  for (let круг = 0; круг < 8; круг++) {
    const беды = проверитьПроходимость(сетка.map((р) => р.join('')));
    if (!беды.length) break;

    for (const беда of беды) {
      // Ряд кромки, от которой прыгают: верхняя твёрдая клетка её колонки.
      let ряд = -1;
      for (let r = 0; r < сетка.length; r++) {
        const з = сетка[r][беда.col];
        if (з === '#' || з === '=' || з === '/' || з === '\\') {
          ряд = r;
          break;
        }
      }
      if (ряд < 0) continue;

      // Островки через каждые три клетки: столько берёт базовый прыжок.
      for (let d = 3; d <= беда.пусто; d += 3) {
        const col = беда.col + d;
        if (col >= сетка[0].length) break;
        if (сетка[ряд][col] === ' ') сетка[ряд][col] = '#';
      }
    }
  }

  return сетка.map((р) => р.join(''));
}

/**
 * Построить рельеф.
 *
 * @returns {{карта: string[], этажей: number}}
 */
export function генерироватьРельеф({
  колонок = 120,
  рядов = 14,
  сложность = 1,
  зерно = 1,
} = {}) {
  const rnd = случай(Number(зерно) || 1);
  const карта = холст(колонок, рядов);

  // Сколько этажей влезет: каждому нужно пять рядов, и ещё три на небо.
  const хочется = ЭТАЖЕЙ[сложность] ?? 1;
  const влезает = Math.max(1, Math.floor((рядов - 4) / МЕЖДУ_ЭТАЖАМИ));
  const этажей = Math.min(хочется, влезает);

  const нижнийРяд = рядов - 3;
  const кромка = 2; // сколько клеток не трогаем у краёв карты

  for (let i = 0; i < этажей; i++) {
    const ряд = нижнийРяд - i * МЕЖДУ_ЭТАЖАМИ;
    // Этажи чередуют направление: пробежал вправо — поднялся — идёшь влево.
    // Поэтому и укорачиваем их с того края, где переход уже был.
    const слева = i === 0 ? кромка : кромка + 4;
    const справа = колонок - 1 - (i === этажей - 1 ? кромка : кромка + 4);
    этаж(карта, {
      от: слева,
      до: справа,
      ряд,
      нижний: i === 0,
      сложность,
      rnd,
    });

    if (i < этажей - 1) {
      // Переход стоит у того края, куда игрок пришёл: чётные этажи он
      // проходит вправо, нечётные — влево.
      const справаЛи = i % 2 === 0;
      const x = справаЛи ? справа - 1 : слева + 1;
      переход(карта, {
        x,
        снизу: ряд,
        сверху: ряд - МЕЖДУ_ЭТАЖАМИ,
        сложность,
        rnd,
      });
    }
  }

  // Старт внизу слева, финиш — в конце последнего этажа.
  поставить(карта, кромка + 1, нижнийРяд - 1, 'P');
  const последний = этажей - 1;
  const рядФиниша = нижнийРяд - последний * МЕЖДУ_ЭТАЖАМИ;
  const финишX =
    последний % 2 === 0 ? колонок - 1 - кромка - 2 : кромка + 3;
  поставить(карта, финишX, рядФиниша - 1, 'F');

  return {
    карта: починить(карта.map((ряд) => ряд.join(''))),
    этажей,
    // На нескольких этажах финиш нельзя засчитывать по одной колонке: игрок
    // проходит её на каждом этаже. Игре об этом говорит правило.
    финишПоВысоте: этажей > 1,
  };
}

/** Длина карты в пикселях — для подписи в редакторе. */
export function вПикселях(колонок) {
  return колонок * КЛЕТКА;
}
