function кнопки() {
  const выбор = document.getElementById('этапы');
  выбор.innerHTML = LEVELS.map((л, i) => `<option value="${i}">${i + 1}. ${л.name}</option>`).join('');
  выбор.addEventListener('change', (e) => открытьЭтап(Number(e.target.value)));

  document.getElementById('открыть').addEventListener('click', () => открытьЭтап(Number(выбор.value)));
  document.getElementById('пол').addEventListener('click', постелитьПол);
  document.getElementById('новый').addEventListener('click', новыйЭтап);
  document.getElementById('глубже').addEventListener('click', глубже);
  document.getElementById('выше').addEventListener('click', выше);
  document.getElementById('сохранить').addEventListener('click', сохранить);
  document.getElementById('сохранитьКак').addEventListener('click', сохранитьФайл);
  document.getElementById('файл').addEventListener('click', открытьФайл);
  document.getElementById('проверить').addEventListener('click', проверить);
  document.getElementById('экспорт').addEventListener('click', экспорт);
  document.getElementById('импорт').addEventListener('click', импорт);
  document.getElementById('играть').addEventListener('click', проба);
  document.getElementById('отменить').addEventListener('click', отменить);
  document.getElementById('вернуть').addEventListener('click', вернуть);
  document.getElementById('шире').addEventListener('click', () => {
    запомнить();
    состояние.карта = состояние.карта.map((с) => с + ПУСТО.repeat(20));
    перерисовать();
  });
  document.getElementById('крупнее').addEventListener('click', () => {
    состояние.масштаб = Math.min(1.2, состояние.масштаб + 0.2);
    перерисовать();
  });
  document.getElementById('мельче').addEventListener('click', () => {
    состояние.масштаб = Math.max(0.3, состояние.масштаб - 0.2);
    перерисовать();
  });
}

/**
 * Испечь текстуры игры.
 *
 * Пхасер рисует их кодом и только внутри сцены, поэтому поднимаем крошечную
 * игру размером 4×4 в невидимом углу: она нужна ровно на один кадр — чтобы
 * отдать нам готовые картинки.
 */
function испечьТекстуры() {
  return new Promise((готово) => {
    const кухня = document.createElement('div');
    кухня.style.display = 'none';
    document.body.append(кухня);
    const игра = new Phaser.Game({
      type: Phaser.CANVAS,
      width: 4,
      height: 4,
      parent: кухня,
      scene: {
        create() {
          createTextures(this);
          готово(игра.textures);
        },
      },
    });
  });
}

async function запуск() {
  // Черновик: обновлённая страница не должна стоить получаса работы.
  const черновик = прочитатьЧерновик();
  const ширинаЧерновика = черновик?.карта[0]?.length ?? 0;
  состояние.карта = черновик ? черновик.карта.slice() : пустаяКарта();
  if (черновик) {
    состояние.состав = { ...состояние.состав, ...(черновик.состав ?? {}) };
    состояние.имяФайла = черновик.имяФайла ?? '';
    состояние.верх = Number(черновик.верх) || 0;
    if (черновик.тест) состояние.тест = { ...состояние.тест, ...черновик.тест };
    if (черновик.детали) состояние.детали = черновик.детали;
    if (черновик.правила) состояние.правила = черновик.правила;
    состояние.опыт = приниматьОпыт(черновик.опыт ?? черновик.финиш) ?? состояние.опыт;
  }

  собратьПалитру();
  собратьПанель();
  собратьСтарт();
  кнопки();
  обновитьИмяФайла();
  выбрать('#');
  перерисовать();
  сказать('Пеку текстуры…');
  текстуры = await испечьТекстуры();
  иконкиПалитры();
  значкиСтарта();
  перерисовать();

  if (черновик) {
    const когда = черновик.когда ? new Date(черновик.когда).toLocaleString('ru') : 'прошлый раз';
    сказать(
      `Восстановлен черновик от ${когда}: ${ширинаЧерновика} клеток. ` +
        'Чистый лист — кнопка «Новый этап»'
    );
    return;
  }
  сказать(
    'Готово. Рисуйте мышью, правая кнопка стирает, Shift заливает столбец до низа. ' +
      'Выделение — стрелкой в «Правке»: Delete удаляет, Ctrl+A/C/X/V/Z/Y как везде'
  );
}

