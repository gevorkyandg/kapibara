/** «1 клетку», «2 клетки», «5 клеток» — число со склонённым словом. */
function считалка(сколько, [одну, две, много]) {
  const n = Math.abs(сколько);
  const е = n % 10;
  const д = n % 100;
  if (е === 1 && д !== 11) return `${n} ${одну}`;
  if (е >= 2 && е <= 4 && (д < 10 || д >= 20)) return `${n} ${две}`;
  return `${n} ${много}`;
}

/** Сколько предметов попало в рамку (пустые клетки не в счёт). */
function сколькоВыделено() {
  const в = нормализовать(состояние.выделение);
  if (!в) return 0;
  let сколько = 0;
  for (let row = в.r1; row <= в.r2; row++) {
    for (let col = в.c1; col <= в.c2; col++) if (взять(col, row) !== ПУСТО) сколько++;
  }
  return сколько;
}

function выделитьВсё() {
  состояние.выделение = { c1: 0, r1: 0, c2: ширина() - 1, r2: рядов() - 1 };
  перерисовать();
  сказать(`Выделено всё: предметов ${сколькоВыделено()}`);
}

function копировать(тихо = false) {
  const в = нормализовать(состояние.выделение);
  if (!в) {
    сказать('Сначала выделите мышью');
    return null;
  }
  состояние.буфер = [];
  for (let row = в.r1; row <= в.r2; row++) {
    let строка = '';
    for (let col = в.c1; col <= в.c2; col++) строка += взять(col, row);
    состояние.буфер.push(строка);
  }
  if (!тихо) сказать(`Скопировано ${в.c2 - в.c1 + 1}×${в.r2 - в.r1 + 1} клеток`);
  return в;
}

function удалитьВыделенное(тихо = false) {
  const в = нормализовать(состояние.выделение);
  if (!в) return сказать('Сначала выделите мышью');
  запомнить();
  for (let row = в.r1; row <= в.r2; row++) {
    for (let col = в.c1; col <= в.c2; col++) положить(col, row, ПУСТО);
  }
  перерисовать();
  if (!тихо) сказать('Удалено');
}

function вырезать() {
  const в = копировать(true);
  if (!в) return;
  удалитьВыделенное(true);
  сказать(`Вырезано ${в.c2 - в.c1 + 1}×${в.r2 - в.r1 + 1} клеток`);
}

/**
 * Вставить из буфера под курсор.
 *
 * По умолчанию пустые клетки буфера не переносятся: чаще всего копируют
 * предмет, а не прямоугольник, и вставленная пустота стёрла бы землю под
 * ним. Кому нужен кусок целиком, вместе с пустотой, — Shift+Ctrl+V.
 */
function вставить(целиком = false) {
  if (!состояние.буфер) return сказать('Буфер пуст');
  запомнить();
  // Выделение — это уже сказанное «сюда», и оно важнее того, где случайно
  // оказалась мышь. Курсор остаётся запасным ответом: выделения нет —
  // кладём под руку.
  const рамка = нормализовать(состояние.выделение);
  const col = рамка ? рамка.c1 : состояние.курсор.col;
  const row = рамка ? рамка.r1 : состояние.курсор.row;
  состояние.буфер.forEach((строка, r) => {
    [...строка].forEach((знак, c) => {
      if (!целиком && знак === ПУСТО) return;
      положить(col + c, row + r, знак);
    });
  });
  состояние.выделение = {
    c1: col,
    r1: row,
    c2: col + состояние.буфер[0].length - 1,
    r2: row + состояние.буфер.length - 1,
  };
  перерисовать();
  сказать(
    целиком
      ? 'Вставлено целиком, вместе с пустотой'
      : 'Вставлено. Shift+Ctrl+V — вставить вместе с пустотой'
  );
}

/**
 * Буква клавиши независимо от раскладки.
 *
 * На русской раскладке Ctrl+C приходит с key = «с», Ctrl+V — с «м», и разбор
 * по key просто не срабатывал: команды молчали. Physical code от раскладки не
 * зависит — KeyC остаётся KeyC хоть на русской, хоть на английской.
 */
function буква(e) {
  if (/^Key[A-Z]$/.test(e.code)) return e.code.slice(3).toLowerCase();
  return e.key.length === 1 ? e.key.toLowerCase() : '';
}

// Прокрутили или изменили окно — перерисовываем: холст показывает только
// видимый кусок карты и должен переехать вслед за глазами.
document.getElementById('поле').addEventListener('scroll', () => перерисовать());
window.addEventListener('resize', () => перерисовать());

window.addEventListener('keydown', (e) => {
  // Пока набирают в поле состава, клавиши принадлежат полю, а не карте.
  // Проверяем через instanceof: у события, пришедшего не от элемента (окно,
  // документ), метода matches нет вовсе, и голая проверка роняла бы весь
  // разбор клавиш молча.
  if (e.target instanceof HTMLElement && e.target.matches('input, textarea, select')) return;

  if (e.ctrlKey || e.metaKey) {
    const дела = {
      z: отменить,
      y: вернуть,
      a: выделитьВсё,
      c: () => копировать(),
      x: вырезать,
      v: () => вставить(e.shiftKey),
    };
    const дело = дела[буква(e)];
    if (дело) {
      e.preventDefault();
      дело();
    }
    return;
  }

  if (e.key === 'Delete' || e.key === 'Backspace') {
    e.preventDefault();
    удалитьВыделенное();
    return;
  }
  if (e.key === 'Escape') {
    состояние.выделение = null;
    перерисовать();
    return;
  }
  if (e.key === ' ') {
    e.preventDefault();
    выбрать(ПУСТО);
    return;
  }
  // Сперва то, что набрано (# ^ ~ * = /  ! — они одинаковы в любой
  // раскладке), потом буква по физической клавише: «m» на русской
  // раскладке приходит как «ь», а клавиша та же.
  const б = буква(e);
  const латиница = e.shiftKey ? б.toUpperCase() : б;
  if (ЗНАКИ.has(e.key)) выбрать(e.key);
  else if (ЗНАКИ.has(латиница)) выбрать(латиница);
});

