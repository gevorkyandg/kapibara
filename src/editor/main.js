/** Прочитать параметры старта из формы, поправив явную чепуху. */
function снятьСтарт() {
  const форма = document.getElementById('стартФорма');
  const данные = new FormData(форма);
  const т = { уровень: 1, предметы: {}, улучшения: {}, жизни: 0 };

  // Уровня ниже первого и выше пятнадцатого не бывает; на всё непонятное
  // отвечаем единицей — с ней этап заведомо проходим без покупок.
  const введено = Number(данные.get('уровень'));
  т.уровень = !Number.isFinite(введено) || введено < 1 ? 1 : Math.min(УРОВЕНЬ_ПРЕДЕЛ, Math.floor(введено));
  форма.уровень.value = т.уровень;

  for (const у of УМЕНИЯ) {
    т.предметы[у.id] = данные.get(`есть:${у.id}`) === 'on';
    т.улучшения[у.id] = Number(данные.get(`ступень:${у.id}`)) || 0;
  }
  т.жизни = Number(данные.get('жизни')) || 0;

  состояние.тест = т;
  записатьЧерновик();
}

