/**
 * Сохранить в файл.
 *
 * Где сможем — просим у браузера настоящее окно сохранения: человек сам
 * выбирает папку и имя. Где такого окна нет (а его нет в части браузеров) —
 * отдаём файл обычной загрузкой, чтобы кнопка работала везде.
 */
async function записатьВ(дескриптор, данные) {
  const поток = await дескриптор.createWritable();
  await поток.write(данные);
  await поток.close();
}

function запомнитьФайл(дескриптор) {
  состояние.дескриптор = дескриптор ?? null;
  состояние.имяФайла = дескриптор?.name ?? '';
  обновитьИмяФайла();
  пометить(false);
  записатьЧерновик();
}

/**
 * Сохранить в свой файл.
 *
 * Пока файла нет — это то же «Сохранить как»: спрашиваем, куда класть. Как
 * только файл назван, кнопка перестаёт спрашивать и просто пишет в него; имя
 * видно наверху, чтобы не гадать, куда уходит работа.
 *
 * После обновления страницы разрешение на запись у браузера пропадает — он
 * не отдаёт его насовсем, — поэтому первое сохранение снова спросит место.
 */
async function сохранить() {
  if (состояние.дескриптор) {
    try {
      const данные = содержимоеФайла();
      await записатьВ(состояние.дескриптор, данные);
      состояние.снимок = данные;
      пометить(false);
      сказать(`Сохранено: ${состояние.имяФайла}`);
      return;
    } catch {
      сказать('В этот файл записать не вышло — спрошу, куда сохранить');
      запомнитьФайл(null);
    }
  }
  await сохранитьФайл();
}

async function сохранитьФайл() {
  const данные = содержимоеФайла();
  const имя = имяФайла();
  try {
    if (window.showSaveFilePicker) {
      const дескриптор = await window.showSaveFilePicker({
        suggestedName: имя,
        types: [{ description: 'Этап капибары', accept: { 'application/json': ['.json'] } }],
      });
      await записатьВ(дескриптор, данные);
      состояние.снимок = данные;
      запомнитьФайл(дескриптор);
      сказать(`Сохранено: ${дескриптор.name}`);
      return;
    }
  } catch (е) {
    if (е.name === 'AbortError') return сказать('Сохранение отменено');
  }
  const ссылка = document.createElement('a');
  ссылка.href = URL.createObjectURL(new Blob([данные], { type: 'application/json' }));
  ссылка.download = имя;
  ссылка.click();
  URL.revokeObjectURL(ссылка.href);
  сказать(`Файл «${имя}» ушёл в загрузки`);
}

async function открытьФайл() {
  try {
    if (window.showOpenFilePicker) {
      const [дескриптор] = await window.showOpenFilePicker({
        types: [{ description: 'Этап капибары', accept: { 'application/json': ['.json'] } }],
      });
      const файл = await дескриптор.getFile();
      принятьФайл(await файл.text(), файл.name);
      состояние.снимок = содержимоеФайла();
      запомнитьФайл(дескриптор);
      return;
    }
  } catch (е) {
    if (е.name === 'AbortError') return сказать('Открытие отменено');
  }
  const поле = document.createElement('input');
  поле.type = 'file';
  поле.accept = '.json,application/json';
  поле.addEventListener('change', async () => {
    const файл = поле.files?.[0];
    if (файл) принятьФайл(await файл.text(), файл.name);
  });
  поле.click();
}

function принятьФайл(текст, имя) {
  let данные;
  try {
    данные = JSON.parse(текст);
  } catch {
    return сказать(`«${имя}» — это не файл этапа`);
  }
  if (!Array.isArray(данные.карта) || !данные.карта.length) {
    return сказать(`В «${имя}» нет карты`);
  }
  запомнить();
  const ш = Math.max(...данные.карта.map((с) => с.length));
  состояние.карта = данные.карта.map((с) => String(с).padEnd(ш, ПУСТО));
  if (данные.состав) состояние.состав = { ...состояние.состав, ...данные.состав };
  состояние.верх = Number(данные.верх) || 0;
  состояние.детали = данные.детали && typeof данные.детали === 'object' ? данные.детали : {};
  состояние.правила = данные.правила && typeof данные.правила === 'object' ? данные.правила : {};
  if (данные.дляТеста) состояние.тест = { ...состояние.тест, ...данные.дляТеста };
  состояние.опыт = приниматьОпыт(данные.опытЗаЗвёзды ?? данные.финиш) ?? состояние.опыт;
  состояние.выделение = null;
  собратьПанель();
  собратьСтарт();
  перерисовать();
  сказать(`Открыт «${данные.название ?? имя}»: ${ширина()} клеток, рядов ${рядов()}`);
}

function постелитьПол() {
  запомнить();
  for (let row = ПОЛ + состояние.верх; row < рядов(); row++) {
    состояние.карта[row] = '#'.repeat(ширина());
  }
  положить(2, ПОЛ + состояние.верх - 1, 'P');
  положить(ширина() - 3, ПОЛ + состояние.верх - 1, 'F');
  перерисовать();
  сказать('Пол постелен, старт и финиш поставлены');
}

/**
 * Черновик в браузере.
 *
 * Обновлённая страница не должна стоить получаса работы. Пишем не на каждый
 * мазок, а через паузу после него: карта в двадцать тысяч клеток — это
 * несколько килобайт, и складывать их шестьдесят раз в секунду ни к чему.
 */
let черновикЖдёт = 0;
function отложитьЧерновик() {
  clearTimeout(черновикЖдёт);
  черновикЖдёт = setTimeout(записатьЧерновик, 700);
}

function записатьЧерновик() {
  сверитьСФайлом();
  try {
    localStorage.setItem(
      КЛЮЧ_ЧЕРНОВИКА,
      JSON.stringify({
        карта: состояние.карта,
        состав: состояние.состав,
        имяФайла: состояние.имяФайла,
        верх: состояние.верх,
        тест: состояние.тест,
        детали: состояние.детали,
        правила: состояние.правила,
        опыт: состояние.опыт,
        когда: Date.now(),
      })
    );
  } catch {
    // Место кончилось или хранилище закрыто — не беда, работа не встанет.
  }
}

function прочитатьЧерновик() {
  try {
    const сырое = localStorage.getItem(КЛЮЧ_ЧЕРНОВИКА);
    if (!сырое) return null;
    const ч = JSON.parse(сырое);
    return Array.isArray(ч.карта) && ч.карта.length ? ч : null;
  } catch {
    return null;
  }
}

/**
 * Отметить, есть ли правки, которых нет в файле.
 *
 * Кнопка «Сохранить» толстеет — но только когда файл есть. У неназванной
 * карты сохранять пока нечего и некуда: подсвечивать кнопку значило бы
 * требовать того, о чём ещё не договорились.
 */
function пометить(грязно) {
  состояние.грязно = грязно;
  const кнопка = document.getElementById('сохранить');
  if (кнопка) кнопка.classList.toggle('несохранено', грязно && !!состояние.дескриптор);
}

/**
 * Сверить нынешнее состояние с тем, что лежит в файле.
 *
 * Отметку о несохранённом ставит каждая правка — так она появляется сразу,
 * без раздумий. А снимается только здесь, сверкой: отменил всё до последнего
 * шага — и в файле опять ровно то же самое, значит и сохранять нечего.
 *
 * Сверяем не на каждый мазок, а вместе с черновиком, через паузу: строка в
 * несколько килобайт складывается быстро, но не шестьдесят же раз в секунду.
 */
function сверитьСФайлом() {
  if (!состояние.дескриптор) return;
  пометить(содержимоеФайла() !== состояние.снимок);
}

function обновитьИмяФайла() {
  const где = document.getElementById('имяФайла');
  где.textContent = состояние.имяФайла || 'без файла';
  где.classList.toggle('серое', !состояние.имяФайла);
}

/**
 * Сообщение в верхней полосе.
 *
 * Гаснет через пару секунд: «отменено» и «сохранено» нужны ровно в тот миг,
 * когда нажали, а висящая полчаса надпись начинает врать — рука давно делает
 * другое, а полоса всё рассказывает про старое.
 */
let словоЖдёт = 0;
function сказать(текст) {
  const где = document.getElementById('строка');
  где.textContent = текст;
  clearTimeout(словоЖдёт);
  словоЖдёт = setTimeout(() => {
    где.textContent = '';
  }, 2000);
}

