// ── Карта ─────────────────────────────────────────────────────────────────

function пустаяКарта(колонок = 120) {
  return new Array(РЯДОВ).fill(null).map(() => ПУСТО.repeat(колонок));
}

function ширина() {
  return состояние.карта[0]?.length ?? 0;
}

/**
 * Высота карты в рядах.
 *
 * У генератора она всегда РЯДОВ, а у рисованного этапа может быть больше:
 * игра берёт высоту мира из самой карты (worldH = длина карты × клетка), так
 * что глубокая пропасть или высокая гора — вопрос лишних рядов, а не правки
 * движка. Пол при этом остаётся на своём месте, ряды прибавляются снизу.
 */
function рядов() {
  return состояние.карта.length;
}

function взять(col, row) {
  return состояние.карта[row]?.[col] ?? ПУСТО;
}

/**
 * Стереть с карты все такие знаки.
 *
 * Нужно старту и финишу: их ровно по одному. Второй старт не «второй выбор»,
 * а неопределённость — игра возьмёт последний по счёту, а рисовавший будет
 * думать про первый.
 */
function убратьВсе(знак) {
  for (let row = 0; row < рядов(); row++) {
    if (!состояние.карта[row].includes(знак)) continue;
    состояние.карта[row] = состояние.карта[row].split(знак).join(ПУСТО);
  }
}

function положить(col, row, знак) {
  if (row < 0 || row >= рядов() || col < 0 || col >= ширина()) return;
  if (знак === 'P' || знак === 'F') убратьВсе(знак);
  const строка = состояние.карта[row];
  if (строка[col] === знак) return;
  состояние.карта[row] = строка.slice(0, col) + знак + строка.slice(col + 1);
}

/**
 * Снимок для отмены. Карта маленькая, поэтому храним её целиком.
 *
 * Новое действие обрывает ветку отменённого: вернуть шаг вперёд после того,
 * как пошли другой дорогой, уже некуда.
 */
function запомнить() {
  состояние.история.push(состояние.карта.slice());
  if (состояние.история.length > 60) состояние.история.shift();
  состояние.будущее.length = 0;
}

function отменить() {
  const прошлое = состояние.история.pop();
  if (!прошлое) return сказать('Отменять нечего');
  состояние.будущее.push(состояние.карта.slice());
  состояние.карта = прошлое;
  перерисовать();
  сказать('Отменено');
}

function вернуть() {
  const впереди = состояние.будущее.pop();
  if (!впереди) return сказать('Возвращать нечего');
  состояние.история.push(состояние.карта.slice());
  состояние.карта = впереди;
  перерисовать();
  сказать('Возвращено');
}

// ── Рисование ─────────────────────────────────────────────────────────────

function картинка(ключ) {
  if (!текстуры || !текстуры.exists(ключ)) return null;
  return текстуры.get(ключ).getSourceImage();
}

function нарисоватьЗнак(знак, col, row, кл, подЗемлёй) {
  if (знак === ПУСТО || знак === undefined) return;
  const опись = ЗНАКИ.get(знак);
  const x = col * кл;
  const y = row * кл;
  if (!опись) {
    ctx.fillStyle = '#d33';
    ctx.fillRect(x + 2, y + 2, кл - 4, кл - 4);
    return;
  }
  // Земля под землёй рисуется без травяной шапки — как в игре.
  const ключ = знак === '#' && подЗемлёй ? 'dirt-0' : опись.тек;
  const img = картинка(ключ) || картинка(опись.тек);
  if (!img) return;
  if (опись.плитка) {
    ctx.drawImage(img, x, y, кл, кл);
  } else {
    const w = img.width * состояние.масштаб;
    const h = img.height * состояние.масштаб;
    ctx.drawImage(img, x + кл / 2 - w / 2, y + кл - h, w, h);
  }
}

function перерисовать() {
  const кл = КЛЕТКА * состояние.масштаб;
  холст.width = Math.max(1, ширина() * кл);
  холст.height = рядов() * кл;

  // Небо и сетка.
  ctx.fillStyle = '#8fd6f2';
  ctx.fillRect(0, 0, холст.width, холст.height);
  ctx.strokeStyle = 'rgba(0,0,0,0.08)';
  ctx.lineWidth = 1;
  for (let c = 0; c <= ширина(); c++) {
    ctx.beginPath();
    ctx.moveTo(c * кл + 0.5, 0);
    ctx.lineTo(c * кл + 0.5, холст.height);
    ctx.stroke();
  }
  for (let r = 0; r <= рядов(); r++) {
    ctx.beginPath();
    ctx.moveTo(0, r * кл + 0.5);
    ctx.lineTo(холст.width, r * кл + 0.5);
    ctx.stroke();
  }

  // Линия пола: подсказка, на какой высоте генератор стелет землю.
  ctx.strokeStyle = 'rgba(40,90,40,0.45)';
  ctx.lineWidth = 2;
  ctx.beginPath();
  ctx.moveTo(0, (ПОЛ + состояние.верх) * кл);
  ctx.lineTo(холст.width, (ПОЛ + состояние.верх) * кл);
  ctx.stroke();

  // Сами знаки. Пока идёт перенос, клетки-источники рисуются пустыми: груз
  // уже в руках, и оставлять его призрак на старом месте нельзя — иначе не
  // видно, что именно переносится.
  const пер = состояние.перенос;
  for (let row = 0; row < рядов(); row++) {
    for (let col = 0; col < ширина(); col++) {
      if (пер && вРамке(рамкаГруза(пер), col, row)) continue;
      нарисоватьЗнак(взять(col, row), col, row, кл, взять(col, row - 1) === '#');
    }
  }

  if (пер) {
    ctx.globalAlpha = 0.9;
    пер.блок.forEach((строка, r) => {
      [...строка].forEach((знак, c) => {
        нарисоватьЗнак(знак, пер.c1 + пер.dc + c, пер.r1 + пер.dr + r, кл, false);
      });
    });
    ctx.globalAlpha = 1;

    // Красная рамка — предупреждение: отпустишь здесь, и перенос отменится.
    const ш = пер.блок[0].length;
    const в = пер.блок.length;
    ctx.lineWidth = 3;
    ctx.strokeStyle = пер.можно ? '#2f6b24' : '#c0392b';
    ctx.strokeRect((пер.c1 + пер.dc) * кл + 1, (пер.r1 + пер.dr) * кл + 1, ш * кл - 2, в * кл - 2);
    if (!пер.можно) {
      ctx.fillStyle = 'rgba(192, 57, 43, 0.28)';
      ctx.fillRect((пер.c1 + пер.dc) * кл, (пер.r1 + пер.dr) * кл, ш * кл, в * кл);
    }
  }

  // Выделение: полупрозрачная рамка поверх карты и обводка каждого попавшего
  // в неё предмета — чтобы было видно не только область, но и что именно
  // уедет по Ctrl+X или пропадёт по Delete.
  const выд = нормализовать(состояние.выделение);
  if (выд) {
    ctx.fillStyle = 'rgba(74, 143, 60, 0.16)';
    ctx.fillRect(выд.c1 * кл, выд.r1 * кл, (выд.c2 - выд.c1 + 1) * кл, (выд.r2 - выд.r1 + 1) * кл);
    ctx.strokeStyle = '#2f6b24';
    ctx.lineWidth = 2;
    for (let row = выд.r1; row <= выд.r2; row++) {
      for (let col = выд.c1; col <= выд.c2; col++) {
        if (взять(col, row) === ПУСТО) continue;
        ctx.strokeRect(col * кл + 2, row * кл + 2, кл - 4, кл - 4);
      }
    }
    ctx.setLineDash([6, 4]);
    ctx.strokeStyle = '#1e4a17';
    ctx.strokeRect(
      выд.c1 * кл + 1,
      выд.r1 * кл + 1,
      (выд.c2 - выд.c1 + 1) * кл - 2,
      (выд.r2 - выд.r1 + 1) * кл - 2
    );
    ctx.setLineDash([]);
  }

  // Линейка поверх карты: номер клетки и пиксель, как в отладочной строке
  // игры — чтобы найденное в игре место находилось и здесь.
  ctx.fillStyle = 'rgba(0,0,0,0.45)';
  ctx.fillRect(0, 0, холст.width, 16);
  ctx.fillStyle = '#fff';
  ctx.font = '10px monospace';
  for (let col = 0; col < ширина(); col += 5) {
    ctx.fillText(`${col}·${col * КЛЕТКА}`, col * кл + 2, 11);
  }

  document.getElementById('размер').textContent =
    `${ширина()} клеток × ${рядов()} рядов · ${ширина() * КЛЕТКА} px`;
  отложитьЧерновик();
}

// ── Работа мышью ──────────────────────────────────────────────────────────

let рисуем = false;
let стираем = false;
let тянем = false; // растягиваем рамку выделения

function клеткаПоСобытию(e) {
  const кл = КЛЕТКА * состояние.масштаб;
  const r = холст.getBoundingClientRect();
  return {
    col: Math.max(0, Math.min(ширина() - 1, Math.floor((e.clientX - r.left) / кл))),
    row: Math.max(0, Math.min(рядов() - 1, Math.floor((e.clientY - r.top) / кл))),
  };
}

/** Привести рамку к виду «левый верх → правый низ». */
function нормализовать(в) {
  if (!в) return null;
  return {
    c1: Math.min(в.c1, в.c2),
    c2: Math.max(в.c1, в.c2),
    r1: Math.min(в.r1, в.r2),
    r2: Math.max(в.r1, в.r2),
  };
}

function мазок(e) {
  const { col, row } = клеткаПоСобытию(e);
  const знак = стираем || состояние.инструмент === 'ластик' ? ПУСТО : состояние.знак;
  if (e.shiftKey && !стираем) {
    // С шифтом столбец заливается до низа: так стелется земля и стены,
    // ради которых иначе пришлось бы щёлкать по каждой клетке.
    for (let r = row; r < рядов(); r++) положить(col, r, знак);
  } else {
    положить(col, row, знак);
  }
  перерисовать();
}

/** Попадает ли клетка в рамку. */
function вРамке(в, col, row) {
  return !!в && col >= в.c1 && col <= в.c2 && row >= в.r1 && row <= в.r2;
}

/** Откуда груз взят: рамка исходного места. */
function рамкаГруза(пер) {
  return {
    c1: пер.c1,
    r1: пер.r1,
    c2: пер.c1 + пер.блок[0].length - 1,
    r2: пер.r1 + пер.блок.length - 1,
  };
}

/**
 * Влезает ли груз на новое место.
 *
 * Наслаиваться предметам нельзя: в одной клетке карты живёт ровно один
 * символ, и «поверх» тут означало бы «вместо» — молча съеденный костёр или
 * монетка. Поэтому перенос на занятое место не разрешается вовсе, и рука
 * узнаёт об этом заранее, по красной рамке, а не постфактум.
 *
 * Своё же исходное место занятым не считается: сдвинуть цепочку на клетку
 * вбок иначе было бы нельзя.
 */
function переносВозможен(пер) {
  const своё = рамкаГруза(пер);
  for (let r = 0; r < пер.блок.length; r++) {
    for (let c = 0; c < пер.блок[r].length; c++) {
      if (пер.блок[r][c] === ПУСТО) continue;
      const col = пер.c1 + пер.dc + c;
      const row = пер.r1 + пер.dr + r;
      if (col < 0 || col >= ширина() || row < 0 || row >= рядов()) return false;
      if (вРамке(своё, col, row)) continue;
      if (взять(col, row) !== ПУСТО) return false;
    }
  }
  return true;
}

/** Снять содержимое рамки как отдельный кусок. */
function снятьБлок(в) {
  const блок = [];
  for (let row = в.r1; row <= в.r2; row++) {
    let строка = '';
    for (let col = в.c1; col <= в.c2; col++) строка += взять(col, row);
    блок.push(строка);
  }
  return блок;
}

холст.addEventListener('contextmenu', (e) => e.preventDefault());
холст.addEventListener('pointerdown', (e) => {
  холст.setPointerCapture(e.pointerId);
  const { col, row } = клеткаПоСобытию(e);

  // Перенос: берём выделенное, а если выделения нет — тот предмет, за
  // который взялись.
  if (состояние.инструмент === 'перенос' && e.button !== 2) {
    let рамка = нормализовать(состояние.выделение);
    if (!вРамке(рамка, col, row)) {
      if (взять(col, row) === ПУСТО) {
        сказать('Возьмитесь за предмет или сперва выделите область');
        return;
      }
      рамка = { c1: col, c2: col, r1: row, r2: row };
      состояние.выделение = рамка;
    }
    состояние.перенос = {
      c1: рамка.c1,
      r1: рамка.r1,
      блок: снятьБлок(рамка),
      захват: { col, row },
      dc: 0,
      dr: 0,
      можно: true,
    };
    перерисовать();
    return;
  }

  // Мышью выделяют, а не рисуют: тянем рамку, как по рабочему столу.
  if (состояние.инструмент === 'мышь' && e.button !== 2) {
    тянем = true;
    состояние.выделение = { c1: col, r1: row, c2: col, r2: row };
    перерисовать();
    return;
  }

  запомнить();
  рисуем = true;
  стираем = e.button === 2 || состояние.инструмент === 'ластик';
  мазок(e);
});
холст.addEventListener('pointermove', (e) => {
  состояние.курсор = клеткаПоСобытию(e);
  const пер = состояние.перенос;
  if (пер) {
    пер.dc = состояние.курсор.col - пер.захват.col;
    пер.dr = состояние.курсор.row - пер.захват.row;
    пер.можно = переносВозможен(пер);
    перерисовать();
    return;
  }
  if (тянем) {
    const { col, row } = состояние.курсор;
    состояние.выделение.c2 = col;
    состояние.выделение.r2 = row;
    перерисовать();
    return;
  }
  if (рисуем) мазок(e);
});
холст.addEventListener('pointerup', () => {
  const пер = состояние.перенос;
  if (пер) {
    состояние.перенос = null;
    if (!пер.можно) {
      перерисовать();
      сказать('Здесь предметы налезут друг на друга — перенос отменён');
      return;
    }
    if (пер.dc || пер.dr) {
      запомнить();
      const своё = рамкаГруза(пер);
      for (let row = своё.r1; row <= своё.r2; row++) {
        for (let col = своё.c1; col <= своё.c2; col++) положить(col, row, ПУСТО);
      }
      пер.блок.forEach((строка, r) => {
        [...строка].forEach((знак, c) => {
          if (знак === ПУСТО) return;
          положить(пер.c1 + пер.dc + c, пер.r1 + пер.dr + r, знак);
        });
      });
      состояние.выделение = {
        c1: своё.c1 + пер.dc,
        c2: своё.c2 + пер.dc,
        r1: своё.r1 + пер.dr,
        r2: своё.r2 + пер.dr,
      };
      const куда = [];
      if (пер.dc) куда.push(Math.abs(пер.dc) + (пер.dc > 0 ? ' вправо' : ' влево'));
      if (пер.dr) куда.push(Math.abs(пер.dr) + (пер.dr > 0 ? ' вниз' : ' вверх'));
      сказать('Перенесено на ' + куда.join(' и ') + ' (клеток)');
    }
    перерисовать();
    return;
  }
  if (тянем) {
    тянем = false;
    const в = нормализовать(состояние.выделение);
    // Щелчок без протяжки — это «снять выделение», а не «выделить одну
    // клетку»: так ведёт себя любой рабочий стол, и рука ждёт того же.
    if (в.c1 === в.c2 && в.r1 === в.r2) {
      состояние.выделение = null;
      перерисовать();
      сказать('Выделение снято');
      return;
    }
    const сколько = сколькоВыделено();
    сказать(
      сколько
        ? `Выделено предметов: ${сколько} (клетки ${в.c1}–${в.c2})`
        : 'Выделено пусто'
    );
  }
  рисуем = false;
});

/** Сколько предметов попало в рамку (пустые клетки не в счёт). */
function сколькоВыделено() {
  const в = нормализовать(состояние.выделение);
  if (!в) return 0;
  let сколько = 0;
  for (let row = в.r1; row <= в.r2; row++) {
    for (let col = в.c1; col <= в.c2; col++) if (взять(col, row) !== ПУСТО) сколько++;
  }
  return сколько;
}

function выделитьВсё() {
  состояние.выделение = { c1: 0, r1: 0, c2: ширина() - 1, r2: рядов() - 1 };
  перерисовать();
  сказать(`Выделено всё: предметов ${сколькоВыделено()}`);
}

function копировать(тихо = false) {
  const в = нормализовать(состояние.выделение);
  if (!в) {
    сказать('Сначала выделите мышью');
    return null;
  }
  состояние.буфер = [];
  for (let row = в.r1; row <= в.r2; row++) {
    let строка = '';
    for (let col = в.c1; col <= в.c2; col++) строка += взять(col, row);
    состояние.буфер.push(строка);
  }
  if (!тихо) сказать(`Скопировано ${в.c2 - в.c1 + 1}×${в.r2 - в.r1 + 1} клеток`);
  return в;
}

function удалитьВыделенное(тихо = false) {
  const в = нормализовать(состояние.выделение);
  if (!в) return сказать('Сначала выделите мышью');
  запомнить();
  for (let row = в.r1; row <= в.r2; row++) {
    for (let col = в.c1; col <= в.c2; col++) положить(col, row, ПУСТО);
  }
  перерисовать();
  if (!тихо) сказать('Удалено');
}

function вырезать() {
  const в = копировать(true);
  if (!в) return;
  удалитьВыделенное(true);
  сказать(`Вырезано ${в.c2 - в.c1 + 1}×${в.r2 - в.r1 + 1} клеток`);
}

/**
 * Вставить из буфера под курсор.
 *
 * По умолчанию пустые клетки буфера не переносятся: чаще всего копируют
 * предмет, а не прямоугольник, и вставленная пустота стёрла бы землю под
 * ним. Кому нужен кусок целиком, вместе с пустотой, — Shift+Ctrl+V.
 */
function вставить(целиком = false) {
  if (!состояние.буфер) return сказать('Буфер пуст');
  запомнить();
  // Выделение — это уже сказанное «сюда», и оно важнее того, где случайно
  // оказалась мышь. Курсор остаётся запасным ответом: выделения нет —
  // кладём под руку.
  const рамка = нормализовать(состояние.выделение);
  const col = рамка ? рамка.c1 : состояние.курсор.col;
  const row = рамка ? рамка.r1 : состояние.курсор.row;
  состояние.буфер.forEach((строка, r) => {
    [...строка].forEach((знак, c) => {
      if (!целиком && знак === ПУСТО) return;
      положить(col + c, row + r, знак);
    });
  });
  состояние.выделение = {
    c1: col,
    r1: row,
    c2: col + состояние.буфер[0].length - 1,
    r2: row + состояние.буфер.length - 1,
  };
  перерисовать();
  сказать(
    целиком
      ? 'Вставлено целиком, вместе с пустотой'
      : 'Вставлено. Shift+Ctrl+V — вставить вместе с пустотой'
  );
}

/**
 * Буква клавиши независимо от раскладки.
 *
 * На русской раскладке Ctrl+C приходит с key = «с», Ctrl+V — с «м», и разбор
 * по key просто не срабатывал: команды молчали. Physical code от раскладки не
 * зависит — KeyC остаётся KeyC хоть на русской, хоть на английской.
 */
function буква(e) {
  if (/^Key[A-Z]$/.test(e.code)) return e.code.slice(3).toLowerCase();
  return e.key.length === 1 ? e.key.toLowerCase() : '';
}

window.addEventListener('keydown', (e) => {
  // Пока набирают в поле состава, клавиши принадлежат полю, а не карте.
  // Проверяем через instanceof: у события, пришедшего не от элемента (окно,
  // документ), метода matches нет вовсе, и голая проверка роняла бы весь
  // разбор клавиш молча.
  if (e.target instanceof HTMLElement && e.target.matches('input, textarea, select')) return;

  if (e.ctrlKey || e.metaKey) {
    const дела = {
      z: отменить,
      y: вернуть,
      a: выделитьВсё,
      c: () => копировать(),
      x: вырезать,
      v: () => вставить(e.shiftKey),
    };
    const дело = дела[буква(e)];
    if (дело) {
      e.preventDefault();
      дело();
    }
    return;
  }

  if (e.key === 'Delete' || e.key === 'Backspace') {
    e.preventDefault();
    удалитьВыделенное();
    return;
  }
  if (e.key === 'Escape') {
    состояние.выделение = null;
    перерисовать();
    return;
  }
  if (e.key === ' ') {
    e.preventDefault();
    выбрать(ПУСТО);
    return;
  }
  // Сперва то, что набрано (# ^ ~ * = /  ! — они одинаковы в любой
  // раскладке), потом буква по физической клавише: «m» на русской
  // раскладке приходит как «ь», а клавиша та же.
  const б = буква(e);
  const латиница = e.shiftKey ? б.toUpperCase() : б;
  if (ЗНАКИ.has(e.key)) выбрать(e.key);
  else if (ЗНАКИ.has(латиница)) выбрать(латиница);
});

