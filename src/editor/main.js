// ── Карта ─────────────────────────────────────────────────────────────────

function пустаяКарта(колонок = 120) {
  return new Array(РЯДОВ).fill(null).map(() => ПУСТО.repeat(колонок));
}

function ширина() {
  return состояние.карта[0]?.length ?? 0;
}

/**
 * Высота карты в рядах.
 *
 * У генератора она всегда РЯДОВ, а у рисованного этапа может быть больше:
 * игра берёт высоту мира из самой карты (worldH = длина карты × клетка), так
 * что глубокая пропасть или высокая гора — вопрос лишних рядов, а не правки
 * движка. Пол при этом остаётся на своём месте, ряды прибавляются снизу.
 */
function рядов() {
  return состояние.карта.length;
}

/**
 * Подробности клетки: сдвиг предмета внутри неё и размах хода платформы.
 *
 * Карта из символов такого сказать не может — в клетке помещается один знак и
 * ни числа рядом с ним, — поэтому подробности живут отдельной таблицей и
 * ходят вместе с картой: в файл, в черновик и в игру.
 */
function детали(col, row) {
  return состояние.детали[`${col}:${row}`];
}

function задатьДетали(col, row, что) {
  const ключ = `${col}:${row}`;
  const было = состояние.детали[ключ] ?? {};
  const стало = { ...было, ...что };
  // Пустые записи не копим: сдвиг в ноль и стандартный размах — это просто
  // отсутствие записи, и в файле им делать нечего.
  if (стало.сдвиг && стало.сдвиг[0] === 0 && стало.сдвиг[1] === 0) delete стало.сдвиг;
  if (стало.размах === РАЗМАХ[взять(col, row)]) delete стало.размах;
  if (Object.keys(стало).length) состояние.детали[ключ] = стало;
  else delete состояние.детали[ключ];
}

/** Перенести подробности вместе с предметом. */
function переставитьДетали(изCol, изRow, вCol, вRow) {
  const ключ = `${изCol}:${изRow}`;
  const что = состояние.детали[ключ];
  delete состояние.детали[ключ];
  if (что) состояние.детали[`${вCol}:${вRow}`] = что;
}

function взять(col, row) {
  return состояние.карта[row]?.[col] ?? ПУСТО;
}

/**
 * Стереть с карты все такие знаки.
 *
 * Нужно старту и финишу: их ровно по одному. Второй старт не «второй выбор»,
 * а неопределённость — игра возьмёт последний по счёту, а рисовавший будет
 * думать про первый.
 */
function убратьВсе(знак) {
  for (let row = 0; row < рядов(); row++) {
    if (!состояние.карта[row].includes(знак)) continue;
    состояние.карта[row] = состояние.карта[row].split(знак).join(ПУСТО);
  }
}

function положить(col, row, знак) {
  if (row < 0 || row >= рядов() || col < 0 || col >= ширина()) return;
  if (знак === 'P' || знак === 'F') убратьВсе(знак);
  const строка = состояние.карта[row];
  if (строка[col] === знак) return;
  // Подробности принадлежали прежнему жильцу клетки: сдвиг монетки не должен
  // достаться костру, который встал на её место.
  delete состояние.детали[`${col}:${row}`];
  состояние.карта[row] = строка.slice(0, col) + знак + строка.slice(col + 1);
}

/**
 * Снимок для отмены. Карта маленькая, поэтому храним её целиком.
 *
 * Новое действие обрывает ветку отменённого: вернуть шаг вперёд после того,
 * как пошли другой дорогой, уже некуда.
 */
function запомнить() {
  пометить(true);
  состояние.история.push(состояние.карта.slice());
  if (состояние.история.length > 60) состояние.история.shift();
  состояние.будущее.length = 0;
}

function отменить() {
  const прошлое = состояние.история.pop();
  if (!прошлое) return сказать('Отменять нечего');
  состояние.будущее.push(состояние.карта.slice());
  состояние.карта = прошлое;
  перерисовать();
  сказать('Отменено');
}

function вернуть() {
  const впереди = состояние.будущее.pop();
  if (!впереди) return сказать('Возвращать нечего');
  состояние.история.push(состояние.карта.slice());
  состояние.карта = впереди;
  перерисовать();
  сказать('Возвращено');
}

// ── Рисование ─────────────────────────────────────────────────────────────

function картинка(ключ) {
  if (!текстуры || !текстуры.exists(ключ)) return null;
  return текстуры.get(ключ).getSourceImage();
}

/** Рельеф держит сетку мира и сдвигаться не может. */
function рельеф(знак) {
  return знак === '#' || знак === '/' || знак === '\\';
}

function нарисоватьЗнак(знак, col, row, кл, подЗемлёй) {
  if (знак === ПУСТО || знак === undefined) return;
  const опись = ЗНАКИ.get(знак);
  const сдвиг = рельеф(знак) ? null : детали(col, row)?.сдвиг;
  const x = col * кл + ((сдвиг?.[0] ?? 0) * кл) / 2;
  const y = row * кл + ((сдвиг?.[1] ?? 0) * кл) / 2;
  if (!опись) {
    ctx.fillStyle = '#d33';
    ctx.fillRect(x + 2, y + 2, кл - 4, кл - 4);
    return;
  }
  // Земля под землёй рисуется без травяной шапки — как в игре.
  const ключ = знак === '#' && подЗемлёй ? 'dirt-0' : опись.тек;
  const img = картинка(ключ) || картинка(опись.тек);
  if (!img) return;
  if (опись.плитка) {
    ctx.drawImage(img, x, y, кл, кл);
  } else {
    const w = img.width * состояние.масштаб;
    const h = img.height * состояние.масштаб;
    ctx.drawImage(img, x + кл / 2 - w / 2, y + кл - h, w, h);
  }
}

/** Где проходит ход платформы на холсте: середина и половина размаха. */
function ходПлатформы(col, row, знак, кл) {
  const д = детали(col, row);
  const размах = д?.размах ?? РАЗМАХ[знак];
  return {
    сx: col * кл + кл / 2 + ((д?.сдвиг?.[0] ?? 0) * кл) / 2,
    сy: row * кл + кл / 2 + ((д?.сдвиг?.[1] ?? 0) * кл) / 2,
    половина: (размах / 2) * состояние.масштаб,
    размах,
  };
}

function концыХода(знак, сx, сy, половина) {
  return знак === '-'
    ? [
        [сx - половина, сy],
        [сx + половина, сy],
      ]
    : [
        [сx, сy - половина],
        [сx, сy + половина],
      ];
}

/**
 * Цвет клетки на схеме.
 *
 * Схема — это не картинка, а чертёж: по ней смотрят на этап целиком и решают,
 * годится дорога или нет. Поэтому не спрайты, а цветные квадратики: земля
 * читается землёй, опасность красным, зверь тёмным, монета золотой точкой.
 */
function цветСхемы(знак) {
  if (знак === '#') return '#8d6b4b';
  if (знак === '=' || знак === 'x' || знак === '-' || знак === '|') return '#7b8a99';
  if (знак === '/' || знак === '\\') return '#6f8f4a';
  if (знак === '^' || знак === '~' || знак === 'v' || знак === 'V' || знак === 'B') return '#d2452f';
  if (знак === 's') return '#39b54a';
  if (знак === 'c') return '#ffffff';
  if (знак === 'o') return '#f2c230';
  if (знак === '*') return '#f193c0';
  if (знак === 'h') return '#e4485b';
  if (знак === 'P') return '#2f6bd8';
  if (знак === 'F') return '#22252b';
  if (знак === '!') return '#c9a227';
  if ('mflebdwjzpH'.includes(знак)) return '#5b2f6b';
  return null;
}

/**
 * Нарисовать схему: весь этап целиком, уменьшенный до ширины окна.
 *
 * Пока схема на экране, холст с картой не показываем вовсе — иначе непонятно,
 * что перед тобой: то, что уже размещено, или то, что ещё предлагают.
 */
function нарисоватьСхему() {
  const карта = состояние.схема.карта;
  const колонок = карта[0].length;
  const рядовСхемы = карта.length;
  // Схему вписываем целиком: и по ширине, и по высоте. Смысл её в том,
  // чтобы весь этап был виден разом, — прокрутка этот смысл убивает.
  const поле = document.getElementById('поле');
  const вширь = Math.floor((поле.clientWidth - 24) / колонок);
  const ввысь = Math.floor((поле.clientHeight - 24) / рядовСхемы);
  const клетка = Math.max(3, Math.min(16, вширь, ввысь));

  холст.width = колонок * клетка;
  холст.height = рядовСхемы * клетка;
  // Схема помещается в окно целиком, поэтому ни прокрутки, ни сдвига.
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  холст.style.left = '0px';
  холст.style.top = '0px';
  const полотно = document.getElementById('полотно');
  полотно.style.width = `${холст.width}px`;
  полотно.style.height = `${холст.height}px`;

  ctx.fillStyle = '#8fd6f2';
  ctx.fillRect(0, 0, холст.width, холст.height);

  for (let row = 0; row < рядовСхемы; row++) {
    for (let col = 0; col < колонок; col++) {
      const цвет = цветСхемы(карта[row][col]);
      if (!цвет) continue;
      ctx.fillStyle = цвет;
      // Мелочи рисуем точкой поменьше, чтобы земля читалась сплошной.
      const мелочь = 'o*hPF!'.includes(карта[row][col]) || 'mflebdwjzpH'.includes(карта[row][col]);
      const отступ = мелочь ? Math.max(0, Math.floor(клетка / 5)) : 0;
      ctx.fillRect(col * клетка + отступ, row * клетка + отступ, клетка - отступ * 2, клетка - отступ * 2);
    }
  }

  document.getElementById('размер').textContent =
    `схема: ${колонок} × ${рядовСхемы} клеток · ${колонок * КЛЕТКА} px`;
}

/**
 * Подогнать холст под видимое окно.
 *
 * Раньше холст был размером во всю карту, и на большой карте это переставало
 * работать вовсе: 600 клеток на масштабе 0.6 — это двадцать одна тысяча
 * пикселей в ширину, а браузер держит около шестнадцати. Дальше он просто
 * отказывается рисовать, и редактор показывает пустоту.
 *
 * Теперь холст всегда размером с окно, а под ним лежит распорка во всю карту
 * — она и даёт полосы прокрутки. Рисуем только то, что видно, со сдвигом на
 * прокрутку: сколько бы клеток ни было, работы всегда на один экран.
 */
function подогнатьХолст() {
  const поле = document.getElementById('поле');
  const кл = КЛЕТКА * состояние.масштаб;
  const полотно = document.getElementById('полотно');

  полотно.style.width = `${Math.max(1, ширина() * кл)}px`;
  полотно.style.height = `${Math.max(1, рядов() * кл)}px`;

  // Пока страница раскладывается, окно бывает нулевым — берём хоть
  // что-нибудь, иначе холст выйдет в пять пикселей и покажет пустоту.
  const окноШ = поле.clientWidth || 800;
  const окноВ = поле.clientHeight || 500;
  const ш = Math.min(окноШ, ширина() * кл);
  const в = Math.min(окноВ, рядов() * кл);
  if (холст.width !== Math.ceil(ш)) холст.width = Math.ceil(ш);
  if (холст.height !== Math.ceil(в)) холст.height = Math.ceil(в);
  холст.style.left = `${поле.scrollLeft}px`;
  холст.style.top = `${поле.scrollTop}px`;

  return { сдвигX: поле.scrollLeft, сдвигY: поле.scrollTop, ш: холст.width, в: холст.height };
}

function перерисовать() {
  if (состояние.схема) {
    нарисоватьСхему();
    return;
  }
  const кл = КЛЕТКА * состояние.масштаб;
  const { сдвигX, сдвигY, ш: виднаШирина, в: виднаВысота } = подогнатьХолст();

  // Дальше рисуем в координатах карты: сдвиг берёт на себя холст.
  ctx.setTransform(1, 0, 0, 1, -сдвигX, -сдвигY);

  // Какие клетки попадают в окно — только их и трогаем.
  const первыйCol = Math.max(0, Math.floor(сдвигX / кл) - 1);
  const последнийCol = Math.min(ширина() - 1, Math.ceil((сдвигX + виднаШирина) / кл));
  const первыйRow = Math.max(0, Math.floor(сдвигY / кл) - 1);
  const последнийRow = Math.min(рядов() - 1, Math.ceil((сдвигY + виднаВысота) / кл));
  const левый = сдвигX;
  const правый = сдвигX + виднаШирина;
  const верхний = сдвигY;
  const нижний = сдвигY + виднаВысота;

  // Небо и сетка.
  ctx.fillStyle = '#8fd6f2';
  ctx.fillRect(левый, верхний, виднаШирина, виднаВысота);
  // Подклетки: каждая клетка делится на четыре. По ним ставятся предметы
  // со сдвигом — и по ним же удобно мерить на глаз.
  ctx.strokeStyle = 'rgba(0,0,0,0.04)';
  ctx.lineWidth = 1;
  for (let c = первыйCol * 2; c <= (последнийCol + 1) * 2; c++) {
    ctx.beginPath();
    ctx.moveTo((c * кл) / 2 + 0.5, верхний);
    ctx.lineTo((c * кл) / 2 + 0.5, нижний);
    ctx.stroke();
  }
  for (let r = первыйRow * 2; r <= (последнийRow + 1) * 2; r++) {
    ctx.beginPath();
    ctx.moveTo(левый, (r * кл) / 2 + 0.5);
    ctx.lineTo(правый, (r * кл) / 2 + 0.5);
    ctx.stroke();
  }

  ctx.strokeStyle = 'rgba(0,0,0,0.08)';
  ctx.lineWidth = 1;
  for (let c = первыйCol; c <= последнийCol + 1; c++) {
    ctx.beginPath();
    ctx.moveTo(c * кл + 0.5, верхний);
    ctx.lineTo(c * кл + 0.5, нижний);
    ctx.stroke();
  }
  for (let r = первыйRow; r <= последнийRow + 1; r++) {
    ctx.beginPath();
    ctx.moveTo(левый, r * кл + 0.5);
    ctx.lineTo(правый, r * кл + 0.5);
    ctx.stroke();
  }

  // Линия пола: подсказка, на какой высоте генератор стелет землю.
  ctx.strokeStyle = 'rgba(40,90,40,0.45)';
  ctx.lineWidth = 2;
  ctx.beginPath();
  ctx.moveTo(левый, (ПОЛ + состояние.верх) * кл);
  ctx.lineTo(правый, (ПОЛ + состояние.верх) * кл);
  ctx.stroke();

  // Сами знаки. Пока идёт перенос, клетки-источники рисуются пустыми: груз
  // уже в руках, и оставлять его призрак на старом месте нельзя — иначе не
  // видно, что именно переносится.
  const пер = состояние.перенос;
  for (let row = первыйRow; row <= последнийRow; row++) {
    for (let col = первыйCol; col <= последнийCol; col++) {
      if (пер && вРамке(рамкаГруза(пер), col, row)) continue;
      нарисоватьЗнак(взять(col, row), col, row, кл, взять(col, row - 1) === '#');
    }
  }

  if (пер) {
    ctx.globalAlpha = 0.9;
    ctx.save();
    if (пер.точный) ctx.translate((пер.сдвиг[0] * кл) / 2, (пер.сдвиг[1] * кл) / 2);
    пер.блок.forEach((строка, r) => {
      [...строка].forEach((знак, c) => {
        нарисоватьЗнак(знак, пер.c1 + пер.dc + c, пер.r1 + пер.dr + r, кл, false);
      });
    });
    ctx.restore();
    ctx.globalAlpha = 1;

    // Красная рамка — предупреждение: отпустишь здесь, и перенос отменится.
    const ш = пер.блок[0].length;
    const в = пер.блок.length;
    ctx.lineWidth = 3;
    ctx.strokeStyle = пер.можно ? '#2f6b24' : '#c0392b';
    ctx.strokeRect((пер.c1 + пер.dc) * кл + 1, (пер.r1 + пер.dr) * кл + 1, ш * кл - 2, в * кл - 2);
    if (!пер.можно) {
      ctx.fillStyle = 'rgba(192, 57, 43, 0.28)';
      ctx.fillRect((пер.c1 + пер.dc) * кл, (пер.r1 + пер.dr) * кл, ш * кл, в * кл);
    }
  }

  // Ход движущихся платформ: зелёная линия с ручками на концах. Показывает
  // стандартный патруль, пока её не потянули, — так видно, куда платформа
  // доедет, ещё до запуска игры.
  for (let row = первыйRow; row <= последнийRow; row++) {
    for (let col = первыйCol; col <= последнийCol; col++) {
      const знак = взять(col, row);
      if (знак !== '-' && знак !== '|') continue;
      const { сx, сy, половина } = ходПлатформы(col, row, знак, кл);
      ctx.strokeStyle = 'rgba(34, 190, 84, 0.9)';
      ctx.lineWidth = 3;
      ctx.beginPath();
      if (знак === '-') {
        ctx.moveTo(сx - половина, сy);
        ctx.lineTo(сx + половина, сy);
      } else {
        ctx.moveTo(сx, сy - половина);
        ctx.lineTo(сx, сy + половина);
      }
      ctx.stroke();
      ctx.fillStyle = '#18a54a';
      for (const [hx, hy] of концыХода(знак, сx, сy, половина)) {
        ctx.beginPath();
        ctx.arc(hx, hy, 5, 0, Math.PI * 2);
        ctx.fill();
      }
    }
  }

  // Выделение: полупрозрачная рамка поверх карты и обводка каждого попавшего
  // в неё предмета — чтобы было видно не только область, но и что именно
  // уедет по Ctrl+X или пропадёт по Delete.
  const выд = нормализовать(состояние.выделение);
  if (выд) {
    ctx.fillStyle = 'rgba(74, 143, 60, 0.16)';
    ctx.fillRect(выд.c1 * кл, выд.r1 * кл, (выд.c2 - выд.c1 + 1) * кл, (выд.r2 - выд.r1 + 1) * кл);
    ctx.strokeStyle = '#2f6b24';
    ctx.lineWidth = 2;
    for (let row = выд.r1; row <= выд.r2; row++) {
      for (let col = выд.c1; col <= выд.c2; col++) {
        if (взять(col, row) === ПУСТО) continue;
        ctx.strokeRect(col * кл + 2, row * кл + 2, кл - 4, кл - 4);
      }
    }
    ctx.setLineDash([6, 4]);
    ctx.strokeStyle = '#1e4a17';
    ctx.strokeRect(
      выд.c1 * кл + 1,
      выд.r1 * кл + 1,
      (выд.c2 - выд.c1 + 1) * кл - 2,
      (выд.r2 - выд.r1 + 1) * кл - 2
    );
    ctx.setLineDash([]);
  }

  // Линейка поверх карты: номер клетки и пиксель, как в отладочной строке
  // игры — чтобы найденное в игре место находилось и здесь.
  ctx.fillStyle = 'rgba(0,0,0,0.45)';
  ctx.fillRect(левый, верхний, виднаШирина, 16);
  ctx.fillStyle = '#fff';
  ctx.font = '10px monospace';
  const первыйЗнак = Math.floor(первыйCol / 5) * 5;
  for (let col = первыйЗнак; col <= последнийCol; col += 5) {
    ctx.fillText(`${col}·${col * КЛЕТКА}`, col * кл + 2, верхний + 11);
  }

  document.getElementById('размер').textContent =
    `${ширина()} клеток × ${рядов()} рядов · ${ширина() * КЛЕТКА} px`;
  отложитьЧерновик();
}

