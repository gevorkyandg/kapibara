/**
 * Принять опыт за звёзды из файла или черновика.
 *
 * Раньше рядом с опытом лежал порог прохождения, и записи той поры выглядели
 * как [{ порог, опыт }]. Читаем и такие: файлы, сохранённые вчера, не должны
 * ломаться от того, что сегодня поле стало проще.
 */
function приниматьОпыт(что) {
  if (!Array.isArray(что) || что.length !== 3) return null;
  return что.map((з, i) =>
    Math.max(0, Number(typeof з === 'object' ? з?.опыт : з) || ОПЫТ_ПО_УМОЛЧАНИЮ[i])
  );
}

/** Прочитать опыт за звёзды. */
function снятьФиниш() {
  const данные = new FormData(document.getElementById('финишФорма'));
  состояние.опыт = ОПЫТ_ПО_УМОЛЧАНИЮ.map((_, i) =>
    Math.max(0, Number(данные.get(`опыт:${i}`)) || 0)
  );
  записатьЧерновик();
}

/** Прочитать параметры старта из формы, поправив явную чепуху. */
function снятьСтарт() {
  const форма = document.getElementById('стартФорма');
  const данные = new FormData(форма);
  const т = { уровень: 1, предметы: {}, улучшения: {}, жизни: 0 };

  // Уровня ниже первого и выше пятнадцатого не бывает; на всё непонятное
  // отвечаем единицей — с ней этап заведомо проходим без покупок.
  const введено = Number(данные.get('уровень'));
  т.уровень = !Number.isFinite(введено) || введено < 1 ? 1 : Math.min(УРОВЕНЬ_ПРЕДЕЛ, Math.floor(введено));
  форма.уровень.value = т.уровень;

  for (const у of УМЕНИЯ) {
    const есть = данные.get(`есть:${у.id}`) === 'on';
    т.предметы[у.id] = есть;
    // Нулевой ступени в списке нет: ноль — это снятая галочка, и выбирать
    // «умение нулевого уровня» отдельным пунктом значило бы спрашивать об
    // одном и том же дважды.
    т.улучшения[у.id] = есть ? Number(данные.get(`ступень:${у.id}`)) || 1 : 0;
    const список = форма.querySelector(`[name="ступень:${у.id}"]`);
    if (список) список.disabled = !есть;
  }
  т.жизни = Number(данные.get('жизни')) || 0;

  состояние.тест = т;
  записатьЧерновик();
}

