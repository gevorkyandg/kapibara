/**
 * Бот-испытатель: аккуратный прохожий, а не спидранер.
 *
 * Зачем он нужен. Этапы собираются генератором, и после каждой правки надо
 * знать три вещи: проходится ли этап вообще, сколько монет с него можно снять
 * и сколько времени занимает честное прохождение. Руками это проверять
 * дольше, чем править.
 *
 * Чего бот НЕ делает. Он не планирует маршрут наперёд и не ищет оптимум: это
 * был бы TAS-поиск, отдельная работа, которая ломается при каждой правке
 * физики. Бот решает по обстановке, кадр за кадром, — примерно как играет
 * внимательный человек, который видит экран на два прыжка вперёд.
 *
 * Главное, чем он «аккуратный»: момент прыжка он считает, а не угадывает.
 * Дуга прыжка известна точно (её задают jumpVelocity и gravity), поэтому для
 * любого препятствия можно посчитать промежуток расстояний, из которого
 * прыжок проносит над ним, — см. окноПрыжка. Оттуда же следует и обратное:
 * если промежуток пуст, перепрыгнуть нельзя вообще, и надо ждать.
 *
 * Игра шагает вручную (game.step) от постоянной точки отсчёта, поэтому два
 * прогона одного этапа подряд дают одинаковый результат.
 */

const TILE = 60;

/** На чём можно стоять. */
const СТОЯЧИЕ = new Set(['#', '=', '/', '\\', 'x', '-', '|']);

/** На что можно приземлиться или от чего оттолкнуться в полёте. */
const ОПОРЫ = new Set([...СТОЯЧИЕ, 'c', 's']);

/** Ширина тела капибары — она входит во все расчёты расхождения. */
const ШИРИНА = 52;

/** Физика прыжка капибары 1-го уровня. */
const ПРЫЖОК_V = 800;
const ТЯЖЕСТЬ = 1750;

/**
 * Сколько пикселей пустоты капибара перелетает на полной скорости. Ключ —
 * насколько выше край, на который приземляемся, в клетках. Замерено в игре.
 */
const ВБОК = { '-2': 240, '-1': 240, 0: 220, 1: 196, 2: 172 };

/** Кого топтать нельзя. */
const КОЛЮЧИЕ = new Set(['e', 'd', 'z']);

/**
 * Из какого промежутка расстояний прыжок проносит над препятствием.
 *
 * Дуга прыжка известна: высота над точкой отталкивания равна v₀·t − g·t²/2.
 * Значит для препятствия высотой h есть два момента — когда капибара
 * поднялась выше него и когда опустилась обратно. Между ними тело обязано
 * целиком миновать препятствие.
 *
 * @param {number} h высота препятствия над ногами, px
 * @param {number} v скорость сближения, px/с
 * @param {number} длина ширина препятствия плюс ширина тела
 * @returns {{от:number, до:number}|null} промежуток зазора; null — не
 *   перепрыгнуть никак
 */
function окноПрыжка(h, v, длина) {
  if (v <= 0) return null;
  const D = ПРЫЖОК_V * ПРЫЖОК_V - 2 * ТЯЖЕСТЬ * Math.max(0, h);
  if (D <= 0) return null; // выше не подняться

  const корень = Math.sqrt(D);
  const от = (v * (ПРЫЖОК_V - корень)) / ТЯЖЕСТЬ;
  const до = (v * (ПРЫЖОК_V + корень)) / ТЯЖЕСТЬ - длина;
  return до >= от ? { от, до } : null;
}

/**
 * Пора ли прыгать: зазор дошёл до середины окна.
 *
 * Прыгать на дальнем краю окна — значит встречать препятствие в самом конце
 * дуги, уже на снижении, и любая мелочь (камень скатился ниже, монстр
 * прибавил ходу) съедает весь запас. Середина окна оставляет запас в обе
 * стороны, и это единственное место, где он есть.
 */
function пора(зазор, окно) {
  return окно !== null && зазор >= окно.от && зазор <= (окно.от + окно.до) / 2;
}

/** Ряд опоры в столбце, если смотреть от ног игрока. */
function опораРяд(scene, col, footRow, набор = СТОЯЧИЕ) {
  if (col < 0 || col >= scene.cols) return null;
  // Начинаем не с верха карты: в пещере первой попадётся не земля, а свод.
  for (let r = Math.max(0, footRow - 4); r < scene.rows; r++) {
    if (набор.has(scene.map[r][col])) return r;
  }
  return null;
}

/**
 * Где на самом деле левый край опоры в этом столбце.
 *
 * Движущаяся площадка ездит на 170 px вбок, и её символ на карте показывает
 * только место, где она родилась. Прыгать надо туда, где она сейчас.
 */
function левыйКрай(scene, col) {
  const x = col * TILE;
  let ближайшая = null;
  scene.movers.children.iterate((m) => {
    if (!m || !m.active) return;
    if (Math.abs(m.x - (x + TILE / 2)) > 260) return;
    if (ближайшая === null || m.body.left < ближайшая) ближайшая = m.body.left;
  });
  return ближайшая ?? x;
}

/**
 * Ближайшая пропасть впереди: где обрыв, куда приземляться и какой перепад.
 *
 * Отсчёт ведём от ЛЕВОГО края тела. Пока левый край ещё на земле, капибара
 * стоит — правый в это время уже висит над пустотой. Если считать от правого,
 * бот решает, что уже летит, и не прыгает вовсе.
 */
function пропастьВпереди(scene, b, footRow) {
  let c = Math.floor(b.left / TILE);
  let крайX;
  let крайRow;

  if (опораРяд(scene, c, footRow) !== null) {
    while (c < scene.cols && опораРяд(scene, c, footRow) !== null) c++;
    if (c >= scene.cols) return null;
    крайX = c * TILE;
    крайRow = опораРяд(scene, c - 1, footRow);
  } else if (scene.ridingMover) {
    // Стоим на движущейся площадке. На карте под ногами пусто: символ «-»
    // отмечает лишь место, где площадка родилась, а она с тех пор уехала на
    // полтора корпуса. Край берём у самой площадки, иначе бот считает, что
    // уже летит, и спокойно сходит с неё в пропасть.
    крайX = scene.ridingMover.body.right;
    крайRow = footRow;
    c = Math.ceil(крайX / TILE);
  } else {
    return null; // и правда летим
  }

  let d = c;
  while (d < scene.cols && опораРяд(scene, d, footRow, ОПОРЫ) === null) d++;
  if (d >= scene.cols) return null;

  return {
    крайX,
    посадкаX: левыйКрай(scene, d),
    dy: крайRow - опораРяд(scene, d, footRow, ОПОРЫ),
  };
}

/** Ближайший висящий шип впереди — тот, под который лучше не забегать. */
function шипВпереди(scene, x) {
  let ближе = null;
  for (const s of scene.dropSpikes) {
    if (s.state !== 'hang' && s.state !== 'shake') continue;
    const d = s.шип.x - x;
    if (d < -40 || d > 420) continue;
    if (!ближе || d < ближе.d) ближе = { d, s };
  }
  return ближе;
}

/**
 * Валун, который сближается с нами, и зазор до него.
 *
 * Важна не сторона, с которой он катится, а скорость сближения: спереди она
 * складывается с бегом, сзади вычитается, и окно прыжка выходит совсем
 * разное — спереди широкое, сзади в несколько кадров.
 */
function валунВпереди(scene, b) {
  let ближе = null;
  scene.boulders.children.iterate((v) => {
    if (!v || !v.active || !v.body) return;
    if (Math.abs(v.y - b.center.y) > 140) return;

    const сзади = v.x < b.center.x;
    const зазор = сзади ? b.left - v.body.right : v.body.left - b.right;
    if (зазор < -30 || зазор > 600) return;

    const сближение = сзади
      ? v.body.velocity.x - scene.walkSpeed
      : scene.walkSpeed - v.body.velocity.x;
    if (сближение <= 0) return;

    if (!ближе || зазор < ближе.зазор) {
      // Высоту меряем от НОГ капибары до верха камня, а не по самому камню.
      // На склоне это совсем разные числа: камень катится по горке выше
      // бегущего, и перепрыгнуть надо не его 54 пикселя, а всю разницу
      // высот. С «высотой камня» бот считал прыжок лёгким и прыгал прямо
      // под него.
      ближе = {
        зазор,
        сближение,
        высота: b.bottom - v.body.top,
        ширина: v.body.width,
      };
    }
  });
  return ближе;
}

/**
 * Ближайшая полоса наземных препятствий: костров или колючек.
 *
 * Полоса — это те, что стоят вплотную: их перепрыгивают одним прыжком или не
 * перепрыгивают вовсе. А вот следующая полоса за просветом — уже отдельное
 * препятствие, и мерить её вместе с первой нельзя: сложив три костра с двумя
 * просветами в одну «ширину», бот получал полосу в 288 пикселей, решал, что
 * перепрыгнуть её нельзя, и топтался на месте перед первым же костром.
 */
function опасностьВпереди(scene, b) {
  const рядом = scene.hazards
    .filter((r) => r.right >= b.right - 20 && r.x - b.right <= 320)
    .filter((r) => r.bottom >= b.top && r.y <= b.bottom + 40)
    .sort((a, c) => a.x - c.x);
  if (!рядом.length) return null;

  let край = рядом[0].right;
  let верх = рядом[0].y;
  for (let i = 1; i < рядом.length; i++) {
    const r = рядом[i];
    if (r.x > край + 40) break; // дальше просвет, а значит другое препятствие
    край = Math.max(край, r.right);
    верх = Math.min(верх, r.y);
  }
  return { зазор: рядом[0].x - b.right, ширина: край - рядом[0].x, высота: b.bottom - верх };
}

/**
 * Монстр на пути и всё, что нужно, чтобы решить, как его миновать.
 *
 * Скорость сближения считаем от обычного бега, а не от той, с которой
 * капибара едет сейчас. Иначе выходит западня: бот притормозил, скорость
 * сближения обнулилась, окна прыжка при нулевой скорости не существует —
 * и он честно ждёт вечно, вместо того чтобы разбежаться и перепрыгнуть.
 */
function монстрВпереди(scene, b) {
  let ближе = null;
  for (const группа of [scene.walkers, scene.flyers]) {
    группа.children.iterate((m) => {
      if (!m || !m.active || !m.body) return;
      const зазор = m.body.left - b.right;
      if (зазор < -30 || зазор > 300) return;

      // Кто пролетает заметно выше или ниже — дорогу не загораживает. Для
      // летающих полосу берём шире: пока капибара добегает, муха успевает
      // опуститься ровно ей навстречу.
      const запас = m.type.ground ? 10 : 90;
      if (m.body.bottom < b.top - запас || m.body.top > b.bottom + 10) return;
      if (!ближе || зазор < ближе.зазор) {
        ближе = {
          вид: m.kind,
          зазор,
          сближение: scene.walkSpeed - m.body.velocity.x,
          высота: b.bottom - m.body.top,
          ширина: m.body.width,
          колючий: КОЛЮЧИЕ.has(m.kind),
        };
      }
    });
  }
  return ближе;
}

/** Монетка, до которой стоит подпрыгнуть. */
function монетаНадГоловой(scene, b) {
  let ближе = null;
  scene.coins.children.iterate((c) => {
    if (!c || !c.active) return;
    const dx = c.x - b.center.x;
    if (dx < -10 || dx > 220) return;
    const выше = b.bottom - c.y;
    if (выше < 50 || выше > 170) return;
    if (ближе === null || dx < ближе) ближе = dx;
  });
  return ближе;
}

/**
 * Одно решение бота: что нажать в этом кадре.
 *
 * Порядок важен — сначала то, что убивает, потом то, что мешает, и только
 * потом монетки.
 */
export function решить(scene) {
  const t = scene.touch;
  const b = scene.player.body;
  t.left = false;
  t.right = true;
  t.jumpQueued = false;
  t.boost = false;

  const наПолу = b.onFloor() || b.blocked.down;
  const footRow = Math.floor(b.bottom / TILE);

  // Пружина держит — жмём прыжок, чтобы вышел заряженный выстрел.
  if (scene.springHold) {
    t.jumpQueued = true;
    return;
  }

  // Висящий шип метит ровно в бегущего, поэтому бежать под ним нельзя.
  // Останавливаемся и ждём, пока сорвётся: это и есть честный способ уйти.
  const шип = шипВпереди(scene, b.center.x);
  if (шип && шип.d > 30 && шип.d < 300) {
    t.right = false;
    return;
  }

  // Валун: прыгаем, когда зазор попал в расчётное окно.
  //
  // И пока камень катится на нас, других причин для прыжка не существует.
  // Прыжок один, длится он почти секунду, и если потратить его на монетку или
  // на ёжика, к моменту встречи с камнем капибара будет уже на земле. Именно
  // так бот и погибал на каждой горке: подпрыгивал загодя и приземлялся ровно
  // под валун.
  const валун = валунВпереди(scene, b);
  if (валун) {
    const окно = окноПрыжка(валун.высота, валун.сближение, валун.ширина + ШИРИНА);
    if (наПолу && пора(валун.зазор, окно)) {
      t.jumpQueued = true;
    }
    return;
  }

  // Пропасть: прыгаем в последний момент, когда под телом ещё есть опора.
  //
  // Капибара стоит, пока хоть край тела лежит на земле, то есть пока левый
  // край не сошёл с обрыва. Каждый лишний пиксель разбега — это лишний
  // пиксель дальности, и на предельных пропастях только он и решает.
  const яма = пропастьВпереди(scene, b, footRow);
  if (яма && наПолу && b.left >= яма.крайX - 16) {
    // Долетим ли отсюда? Оттолкнуться можно, пока левый край на земле, то
    // есть правый край будет примерно на «крайX + ширина тела».
    const предел = ВБОК[Math.max(-2, Math.min(2, яма.dy))] ?? ВБОК[2];
    const долетим = яма.посадкаX + 20 <= яма.крайX + ШИРИНА + предел;

    if (долетим) {
      t.jumpQueued = true;
      return;
    }

    // Не долетим — значит опора ещё не подошла: движущаяся площадка уехала в
    // дальний конец своего отрезка. Стоим у самого края и ждём её. Прыгать
    // «на авось» здесь нельзя: под ногами сплошная пропасть.
    t.right = false;
    return;
  }

  if (!наПолу) return;

  // Монстр на пути.
  const монстр = монстрВпереди(scene, b);
  if (монстр) {
    const окно = окноПрыжка(монстр.высота, монстр.сближение, монстр.ширина + ШИРИНА);

    if (пора(монстр.зазор, окно)) {
      t.jumpQueued = true;
      return;
    }

    // Окна нет вовсе — значит монстр уходит от нас в ту же сторону или висит
    // прямо на дороге. Догонять его нельзя: приземлимся ему на спину, а
    // спина у половины из них колючая. Ждём, пока развернётся или отплывёт.
    if (!окно && монстр.зазор < 220) {
      t.right = false;
      return;
    }

    // Окно есть, но мы уже ближе его начала — стоим и ждём, пока монстр
    // отойдёт. Пятиться нельзя: назад тоже дорога, и там свои опасности.
    if (окно && монстр.зазор < окно.от) {
      t.right = false;
      return;
    }
  }

  // Костёр и колючки: то же окно, только препятствие стоит на месте.
  const опасно = опасностьВпереди(scene, b);
  if (опасно) {
    const окно = окноПрыжка(опасно.высота, scene.walkSpeed, опасно.ширина + ШИРИНА);
    if (пора(опасно.зазор, окно)) {
      t.jumpQueued = true;
      return;
    }
    if (опасно.зазор < (окно ? окно.от : 20)) {
      t.right = false;
      t.left = true;
      return;
    }
  }

  // Монетку берём, только если впереди чисто: прыжок за монеткой сажает
  // капибару в воздух ровно там, где нужен прыжок через яму или костёр.
  const чисто =
    (!яма || яма.крайX - b.right > 260) && (!опасно || опасно.зазор > 260) && !монстр;
  const монета = монетаНадГоловой(scene, b);
  if (чисто && монета !== null && монета < 60) {
    t.jumpQueued = true;
  }
}

/** Ключ сохранения — прогон обязан вернуть его нетронутым. */
const СОХРАНЕНИЕ = 'capybara-save';

/**
 * Прогнать этап целиком.
 *
 * Две вещи, без которых замеры врут.
 *
 * Первая: герой всегда одного и того же уровня. По умолчанию первого — того,
 * под который считаны все числа проходимости. Иначе выходит западня: бот
 * зарабатывает опыт своими же прогонами, к пятому запуску капибара уже
 * шестого уровня, бегает на 30 px/с быстрее и прыгает дальше, и «этап
 * проходится» означает совсем не то, что означало на первом запуске.
 *
 * Вторая: сохранение игрока возвращается на место. Прогон — это проверка, а
 * не игра, и чужой прогресс он портить не должен.
 *
 * @param {Phaser.Game} game
 * @param {number} levelIndex
 * @param {object} опции кадров, уровень (уровень героя, по умолчанию 1)
 * @returns {Promise<object>} отчёт: прошёл ли, время, монеты, где умирал
 */
export async function прогон(game, levelIndex, опции = {}) {
  const предел = опции.кадров ?? 40000;
  const dt = 1000 / 60;
  const сохранение = localStorage.getItem(СОХРАНЕНИЕ);

  // Время отсчитываем от постоянной точки, а не от того, сколько игра уже
  // проработала: осы и мухи качаются по синусу от абсолютного времени, и без
  // этого два прогона одного этапа расходятся.
  game.loop.sleep();
  let t = 10000;
  const шаг = () => {
    t += dt;
    game.step(t, dt);
  };

  // Гасим всё, что запущено, и обязательно даём кадр на разбор очереди.
  // Иначе «стоп» прошлой сцены приходит уже после того, как новая создалась,
  // и убивает её: объекты на месте, а физических тел у них больше нет.
  game.scene.getScenes(true).forEach((s) => s.scene.stop());
  шаг();

  game.scene.start('GameScene', { levelIndex });
  let scene = null;
  for (let i = 0; i < 90; i++) {
    шаг();
    scene = game.scene.getScene('GameScene');
    if (scene?.player?.body && scene.scene.isActive()) break;
  }
  if (!scene?.player?.body) throw new Error('сцена не поднялась');

  // Приводим героя к нужному уровню поверх того, что лежит в сохранении.
  const уровень = опции.уровень ?? 1;
  scene.walkSpeed = 240 + (уровень - 1) * 6;
  scene.jumpVelocity = -800 - Math.floor((уровень - 1) / 2) * 10;
  scene.maxLives = 2 + Math.floor(уровень / 5);
  scene.lives = scene.maxLives;
  scene.updateHearts();

  let жизни = scene.lives;
  const смерти = [];
  let дальше = scene.player.x;
  let стоитС = 0;
  let кадров = 0;

  for (; кадров < предел; кадров++) {
    решить(scene);
    шаг();

    if (scene.lives < жизни) {
      жизни = scene.lives;
      смерти.push(Math.round(scene.player.x));
    }
    if (scene.finished) break;

    // Застряли: за десять секунд не продвинулись ни на шаг.
    if (scene.player.x > дальше + 4) {
      дальше = scene.player.x;
      стоитС = кадров;
    } else if (кадров - стоитС > 600) {
      break;
    }
  }

  // Возвращаем сохранение как было: прогон начислил монеты и опыт, а это
  // проверка, а не игра.
  if (сохранение === null) localStorage.removeItem(СОХРАНЕНИЕ);
  else localStorage.setItem(СОХРАНЕНИЕ, сохранение);

  return {
    этап: levelIndex,
    герой: уровень,
    прошёл: scene.player.x >= (scene.finishX ?? Infinity),
    смертей: смерти.length,
    смерти,
    монет: `${scene.coinsCollected} / ${scene.totalCoins}`,
    доля: scene.totalCoins ? +(scene.coinsCollected / scene.totalCoins).toFixed(2) : 1,
    секунд: +(кадров / 60).toFixed(1),
    лимит: Math.round((scene.timeLimitMs ?? 0) / 1000),
    дошёлДо: Math.round(scene.player.x),
    длина: scene.worldW,
  };
}
