/**
 * Сбор статистики о том, как в игру играют.
 *
 * Зачем. После выхода мы перестаём видеть игру глазами: бот проходит этап
 * идеально, а живой человек застревает там, где мы этого не ждали. Пять
 * вопросов, ради которых всё это и делается: сколько занимает прохождение,
 * сколько раз умирают, где именно, какие монеты не собирают и кто чаще
 * убивает.
 *
 * Как устроено. Одна запись на попытку прохождения, отправляется один раз в
 * конце. Никаких запросов по ходу игры: на плохой связи они мешали бы играть,
 * а нам нужен только итог.
 *
 * Куда уходит. Прямо в базу Supabase, своего сервера у нас нет и не нужно:
 * браузер пишет в неё через её же адрес. Ключ, который лежит здесь, — тот,
 * что и задуман публичным: у него есть право только добавлять записи и нет
 * права читать. Никто не прочитает чужие данные, даже подсмотрев ключ.
 *
 * Что НЕ собираем: ничего, что относится к человеку. Ни имени, ни почты, ни
 * адреса. Номер игрока — случайное число, живёт в его же браузере и нужно
 * ровно для одного: отличить десять попыток одного человека от одной попытки
 * десяти разных.
 */

import { СТАТИСТИКА } from './config.js';

/** Где лежит номер игрока и очередь неотправленного. */
const КЛЮЧ_ИГРОКА = 'capybara-player';
const КЛЮЧ_ОЧЕРЕДИ = 'capybara-telemetry';

/**
 * Сколько записей держим в очереди, если отправить не вышло.
 *
 * Очередь нужна, потому что связь рвётся, а расширения-блокировщики режут
 * запросы к чужим доменам. Без неё данные таких игроков пропадали бы совсем,
 * и картина перекашивалась бы в сторону тех, у кого всё хорошо.
 */
const ОЧЕРЕДЬ_МАКС = 20;

/** Сколько смертей записываем подробно. Дальше считаем только числом. */
const СОБЫТИЙ_МАКС = 40;

/**
 * Версия игры, с которой снята запись: по ней сравниваем «до» и «после».
 *
 * К запускам с сервера разработки приписывается «-dev». Это наши с вами
 * проверки, и в общей статистике они мусор: тридцать забегов бота выглядят
 * как тридцать игроков и перекашивают средние. Отличать их надо не сегодня, а
 * всегда, поэтому пометка живёт прямо в записи, а не в памяти.
 */
const СБОРКА =
  (typeof __СБОРКА__ === 'string' ? __СБОРКА__ : 'unknown') +
  (import.meta.env.DEV ? '-dev' : '');

/** Работает ли сбор вообще. Без адреса и ключа — нет, и это нормально. */
function включено() {
  return Boolean(СТАТИСТИКА.адрес && СТАТИСТИКА.ключ);
}

/** Хранилище может быть недоступно: приватное окно, запрет на сайт. */
function прочитать(ключ) {
  try {
    return localStorage.getItem(ключ);
  } catch {
    return null;
  }
}

function записать(ключ, значение) {
  try {
    localStorage.setItem(ключ, значение);
  } catch {
    /* некуда писать — переживём */
  }
}

/** Случайный номер игрока. Заводится один раз и живёт в его браузере. */
function номерИгрока() {
  let номер = прочитать(КЛЮЧ_ИГРОКА);
  if (номер) return номер;

  номер =
    typeof crypto !== 'undefined' && crypto.randomUUID
      ? crypto.randomUUID()
      : `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
  записать(КЛЮЧ_ИГРОКА, номер);
  return номер;
}

// ── Очередь ────────────────────────────────────────────────────────────────

function очередь() {
  try {
    const сырое = прочитать(КЛЮЧ_ОЧЕРЕДИ);
    const список = сырое ? JSON.parse(сырое) : [];
    return Array.isArray(список) ? список : [];
  } catch {
    return [];
  }
}

function положитьВОчередь(запись) {
  const список = очередь();
  список.push(запись);
  // Держим только последние: старые данные всё равно относятся к другой
  // версии игры, и толку от них меньше, чем места они занимают.
  записать(КЛЮЧ_ОЧЕРЕДИ, JSON.stringify(список.slice(-ОЧЕРЕДЬ_МАКС)));
}

/**
 * Отправить пачку записей.
 *
 * keepalive нужен, чтобы запрос дожил до конца, даже если вкладку закрывают
 * прямо сейчас: обычный fetch в этот момент отменяется вместе со страницей.
 */
async function отправить(записи) {
  if (!записи.length) return true;

  try {
    const ответ = await fetch(`${СТАТИСТИКА.адрес}/rest/v1/${СТАТИСТИКА.таблица}`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        apikey: СТАТИСТИКА.ключ,
        Authorization: `Bearer ${СТАТИСТИКА.ключ}`,
        Prefer: 'return=minimal',
      },
      body: JSON.stringify(записи),
      keepalive: true,
    });
    return ответ.ok;
  } catch {
    return false;
  }
}

/** Разобрать очередь при запуске игры: что не ушло в прошлый раз — уйдёт сейчас. */
export async function разобратьОчередь() {
  if (!включено()) return;
  const список = очередь();
  if (!список.length) return;

  if (await отправить(список)) записать(КЛЮЧ_ОЧЕРЕДИ, '[]');
}

// ── Одна попытка прохождения ───────────────────────────────────────────────

/**
 * Начать запись о попытке. Возвращает саму запись — её потом дополняют и
 * закрывают. Если сбор выключен, возвращается null, и все остальные функции
 * с ним ничего не делают: игре не нужно знать, включена статистика или нет.
 */
export function начатьЗабег(данные) {
  if (!включено()) return null;

  return {
    player: номерИгрока(),
    build: СБОРКА,
    route: данные.маршрут,
    stage: данные.этап,
    hero_level: данные.уровеньГероя,
    lives_max: данные.жизней,
    abilities: данные.способности,
    coins_total: данные.монетВсего,
    outcome: 'quit',
    ms: 0,
    deaths: 0,
    coins_taken: 0,
    coins_missed: [],
    stars: 0,
    events: [],
  };
}

/**
 * Записать смерть: когда, где и от чего.
 *
 * Координаты — то, ради чего всё затевалось: по ним строится карта мест, где
 * умирают чаще всего. Причина отвечает на второй вопрос: кто именно убивает.
 */
export function отметитьСмерть(забег, { мс, x, y, от }) {
  if (!забег) return;
  забег.deaths += 1;
  if (забег.events.length >= СОБЫТИЙ_МАКС) return;
  забег.events.push({ t: Math.round(мс), x: Math.round(x), y: Math.round(y), by: от });
}

/**
 * Закрыть запись и отправить.
 *
 * Не ушло — ляжет в очередь и уйдёт при следующем запуске игры.
 */
export function закончитьЗабег(забег, итог) {
  if (!забег) return;

  забег.outcome = итог.исход;
  забег.ms = Math.round(итог.мс);
  забег.coins_taken = итог.монетВзято;
  забег.coins_missed = итог.монетМимо;
  забег.stars = итог.звёзд ?? 0;

  отправить([забег]).then((ушло) => {
    if (!ушло) положитьВОчередь(забег);
  });
}
