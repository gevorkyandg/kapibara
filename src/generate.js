/**
 * Сборка этапа из участков.
 *
 * Этап описан не картинкой в символах, а списком участков: «равнина на 10
 * клеток», «пропасть в 3 клетки», «сплошная пропасть из четырёх движущихся
 * платформ, на двух пчёлы». Генератор выкладывает их слева направо, разводит
 * промежутками и досыпает ровной земли до нужной длины.
 *
 * Три правила, на которых всё держится.
 *
 * 1. **Карта обязана получаться одинаковой каждый раз.** Монеты считаются
 *    отдельным проходом (countCoins), и если бы генератор бросал кости заново,
 *    рейтинг за этап расходился бы с тем, что на карте лежит. Весь случай идёт
 *    через seed этапа, и бросается он только на длину промежутков.
 *
 * 2. **Что попало на карту — стоит намертво.** Ни монстр, ни сладость не
 *    решаются в момент игры. Иначе один и тот же этап у одного игрока
 *    проходится, а у другого нет, и бота нельзя прогнать дважды одинаково.
 *
 * 3. **Проходимость считается, а не угадывается.** После сборки отдельный
 *    проход измеряет каждый переход между опорами и сверяет с замеренной
 *    дальностью прыжка. Непосильный переход — это ошибка сборки, а не
 *    «повезёт-не повезёт».
 *
 * Все числа проходимости замерены в самой игре на капибаре 1-го уровня, а не
 * выведены из формул: см. ПРЫЖОК ниже.
 */

/** Высота этапа в клетках и ряд, на котором лежит поверхность земли. */
export const РЯДОВ = 14;
export const ПОЛ = 11;



/**
 * Что капибара 1-го уровня может, разогнавшись до обычного бега (240 px/с).
 * Замерено в игре: держим «вправо», прыгаем с края и смотрим, куда попадаем.
 *
 * Ключ — насколько выше край, на который приземляемся, в клетках. Значение —
 * сколько пикселей пустоты можно перелететь.
 */
export const ПРЫЖОК = {
  вверх: 176,
  вбок: { '-1': 240, 0: 220, 1: 196, 2: 172 },
};

/** Пружина: подбрасывает на столько пикселей от своего верха. */
export const ПРУЖИНА = { сНажатием: 340, без: 124 };

/** Сколько пикселей в клетке. Держим здесь, чтобы не тащить config. */
const КЛЕТКА = 60;

/**
 * Стандартная длина этапа в клетках. Множитель длины из описания считается от
 * неё: 1 — стандарт, 1.2 — плюс пятая часть, 2.5 — два с половиной стандарта.
 */
export const ДЛИНА = 120;

/** Генератор случайных чисел с зерном: одинаковый seed — одна и та же карта. */
function случай(seed) {
  let s = (seed * 2654435761) >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5;
    s >>>= 0;
    return s / 4294967296;
  };
}

// ── Холст ──────────────────────────────────────────────────────────────────

/**
 * Холст — растущий вправо список колонок. Колонка это массив символов сверху
 * вниз, по одному на ряд.
 *
 * Отдельно холст помнит текущий уровень земли: после горы с пружиной вся
 * дорога идёт выше, и участки, которые кладутся дальше, обязаны знать об этом.
 */
function холст() {
  return { колонки: [], пол: ПОЛ };
}

function пусто() {
  return new Array(РЯДОВ).fill(' ');
}

/**
 * Колонка земли: от поверхности до самого низа карты.
 *
 * Заливаем целиком, а не тонким пластом. После горы дорога идёт выше, и
 * тонкий пласт оставил бы под ней дыру: сверху плато, снизу пустота — видно,
 * что мир держится ни на чём.
 */
function землёй(полРяд) {
  const c = пусто();
  for (let r = полРяд; r < РЯДОВ; r++) c[r] = '#';
  return c;
}

function добавить(h, колонка) {
  h.колонки.push(колонка);
  return h.колонки.length - 1;
}

/** Индекс последней выложенной колонки. */
function конец(h) {
  return h.колонки.length - 1;
}

/**
 * Записать символ в колонку. Пишем поверх пустоты: если там уже что-то стоит,
 * ищем ближайший свободный ряд выше — иначе монстр молча съедает монетку.
 */
function положить(h, col, ряд, ch) {
  const c = h.колонки[col];
  if (!c) return false;
  let r = ряд;
  while (r >= 0 && c[r] !== ' ') r--;
  if (r < 0) return false;
  c[r] = ch;
  return true;
}

/** Ряд первого непустого символа сверху — где бы ни стояла опора. */
function рядСимвола(h, col) {
  const c = h.колонки[col];
  if (!c) return -1;
  for (let r = 0; r < РЯДОВ; r++) if (c[r] !== ' ') return r;
  return -1;
}

/** Ряд поверхности в этой колонке: первая твёрдая клетка сверху. */
function поверхность(h, col) {
  const c = h.колонки[col];
  if (!c) return РЯДОВ;
  for (let r = 0; r < РЯДОВ; r++) {
    if (c[r] === '#' || c[r] === '=' || c[r] === '/' || c[r] === '\\') return r;
  }
  return РЯДОВ; // пропасть
}

// ── Участки ────────────────────────────────────────────────────────────────
//
// Каждый строитель дописывает свои колонки в холст и возвращает диапазон
// [первая, последняя] — по нему потом расставляются монстры и монетки.

function равнина(h, n) {
  const от = h.колонки.length;
  for (let i = 0; i < n; i++) добавить(h, землёй(h.пол));
  return [от, конец(h)];
}

/**
 * Пропасть: n пустых колонок, а земля за ней — на dy клеток выше (dy < 0 —
 * ниже). Ширина проверяется отдельным проходом, здесь просто кладём.
 */
function пропасть(h, n, dy = 0) {
  const от = h.колонки.length;
  for (let i = 0; i < n; i++) добавить(h, пусто());
  h.пол -= dy;
  return [от, конец(h)];
}

/**
 * Островок над пропастью — парящая площадка в n клеток. Земли под ней нет,
 * упасть мимо значит упасть насовсем.
 */
function островок(h, n, подъём = 0) {
  const от = h.колонки.length;
  const ряд = h.пол - подъём;
  for (let i = 0; i < n; i++) {
    const c = пусто();
    c[ряд] = '=';
    добавить(h, c);
  }
  return [от, конец(h)];
}

/** Одна колонка с парящим предметом на заданной высоте над уровнем земли. */
function парящий(h, ch, надПолом) {
  const c = пусто();
  c[h.пол - надПолом] = ch;
  return добавить(h, c);
}

/**
 * Сплошная пропасть: чередование пустоты и опор. Опоры задаются списком —
 * каждая это { вид, ширина }, где вид определяет, из чего она сделана.
 *
 * Это главный строитель поздних этапов: «сплошная пропасть из четырёх
 * движущихся платформ» или «все островки из падающих платформ, на каждой по
 * монетке» — один и тот же вызов с разными опорами.
 */
function сплошная(h, звенья) {
  const от = h.колонки.length;
  const опоры = [];
  for (const з of звенья) {
    if (з.пропасть) пропасть(h, з.пропасть);
    if (!з.вид) continue;

    const ширина = з.ширина ?? 1;
    const подъём = з.подъём ?? 0;
    const первая = h.колонки.length;

    // На что встают ногами — кладём вровень с землёй, чтобы прыжок через
    // пропасть считался как обычный. Облачко и пружина живут выше: в них
    // влетают на подъёме дуги, а не приземляются сверху.
    if (з.вид === 'островок') островок(h, ширина, подъём);
    else if (з.вид === 'падающая') for (let i = 0; i < ширина; i++) парящий(h, 'x', подъём);
    else if (з.вид === 'движущаяся') for (let i = 0; i < ширина; i++) парящий(h, '-', подъём);
    else if (з.вид === 'облачко') for (let i = 0; i < ширина; i++) парящий(h, 'c', 1 + подъём);
    else if (з.вид === 'пружина') for (let i = 0; i < ширина; i++) парящий(h, 's', 1 + подъём);

    опоры.push({ вид: з.вид, от: первая, до: конец(h), монета: з.монета });
  }
  return { диапазон: [от, конец(h)], опоры };
}

/**
 * Горка со склонами и валунами. Валун сам решает, откуда прикатиться —
 * спереди или сзади, — а метка «B» только говорит, где он должен настичь
 * игрока. Сколько меток подряд, столько валунов в заходе.
 */
function горка(h, { вверх = 3, площадка = 6, валунов = 1 }) {
  const от = h.колонки.length;

  for (let i = 0; i < вверх; i++) {
    const ряд = h.пол - i;
    const c = землёй(ряд);
    c[ряд] = '/';
    добавить(h, c);
  }
  h.пол -= вверх;

  const верх = h.колонки.length;
  for (let i = 0; i < площадка; i++) добавить(h, землёй(h.пол));

  // Метки валунов ставим посередине площадки, подряд.
  const метка = верх + Math.max(0, Math.floor((площадка - валунов) / 2));
  for (let i = 0; i < валунов; i++) положить(h, метка + i, h.пол - 1, 'B');

  for (let i = 0; i < вверх; i++) {
    const ряд = h.пол + i;
    const c = землёй(ряд);
    c[ряд] = '\\';
    добавить(h, c);
  }
  h.пол += вверх;
  добавить(h, землёй(h.пол));

  return [от, конец(h)];
}

/**
 * Пещера: над дорогой каменный свод, с него срываются шипы.
 *
 * Свод нужен не для красоты. Шип обязан быть выбором «пробежать или
 * притормозить», а не «перепрыгнуть»: без потолка игрок просто прыгает через
 * него, и вся механика пропадает. Потолок висит ровно так, чтобы прыжок под
 * ним не проходил.
 */
function пещера(h, { клеток = 12, шипов = 2 }) {
  const от = h.колонки.length;
  const сводНиз = h.пол - 5; // нижний ряд свода
  const шипРяд = h.пол - 4;

  for (let i = 0; i < клеток; i++) {
    const c = землёй(h.пол);
    for (let r = Math.max(0, сводНиз - 2); r <= сводНиз; r++) c[r] = '#';
    добавить(h, c);
  }

  // Шипы разводим по длине пещеры, не ставя их вплотную ко входу.
  const шаг = Math.floor((клеток - 4) / Math.max(1, шипов));
  for (let i = 0; i < шипов; i++) {
    положить(h, от + 2 + i * шаг, шипРяд, 'V');
  }

  return [от, конец(h)];
}

/**
 * Гора с пружиной: отвесная стена, на которую не забраться, пружина перед ней
 * и монетки над пружиной. После горы дорога идёт выше — и финиш тоже.
 *
 * Высоту берём с запасом: прыжок поднимает на 176 px, заряженная пружина на
 * 340. Стена в 4 клетки (240 px) обычным прыжком не берётся, а пружиной
 * берётся уверенно.
 */
function гораСПружиной(h, { высота = 4, разбег = 4 } = {}) {
  const от = h.колонки.length;

  равнина(h, разбег);
  const пружинаCol = конец(h); // последняя ровная клетка перед стеной
  положить(h, пружинаCol, h.пол - 1, 's');

  // Монетки столбиком над пружиной — их не достать без её помощи.
  for (const высь of [3, 4, 5]) положить(h, пружинаCol, h.пол - высь, 'o');

  // Тело горы: сплошное от плато до низа карты, обойти нельзя.
  const верх = h.пол - высота;
  for (let i = 0; i < 4; i++) добавить(h, землёй(верх));
  h.пол = верх;

  return [от, конец(h)];
}

/** Пружина на равнине с монетками наверху — только ради монеток. */
function пружинаСМонетами(h, { монет = 3 } = {}) {
  const от = h.колонки.length;
  равнина(h, 3);
  const col = h.колонки.length - 2;
  положить(h, col, h.пол - 1, 's');
  for (let i = 0; i < монет; i++) положить(h, col, h.пол - 3 - i, 'o');
  равнина(h, 2);
  return [от, конец(h)];
}

// ── Расстановка на готовом рельефе ─────────────────────────────────────────

/** Летающие живут в воздухе, ходячие — на поверхности. */
const ЛЕТАЮЩИЕ = new Set(['f', 'b', 'w']);

/**
 * Разложить монстров по участку. Ходячие встают на поверхность, летающие
 * висят над ней; и те и другие разводятся по ширине участка, чтобы не
 * оказаться в одной точке.
 */
function расставитьМонстров(h, [от, до], список) {
  if (!список || !список.length) return;
  const шаг = (до - от + 1) / (список.length + 1);
  список.forEach((кто, i) => {
    const col = Math.round(от + шаг * (i + 1));
    const пов = поверхность(h, col);
    if (ЛЕТАЮЩИЕ.has(кто)) {
      положить(h, col, (пов === РЯДОВ ? h.пол : пов) - 3, кто);
    } else if (пов < РЯДОВ) {
      положить(h, col, пов - 1, кто);
    }
  });
}

/** То же для препятствий на земле: костров и колючек. */
function расставитьПрепятствия(h, [от, до], список, подряд = false) {
  if (!список || !список.length) return;

  // «Подряд» — это отдельная просьба: два костра вплотную читаются как одно
  // длинное препятствие, через которое нужен разбег, а те же два костра
  // вразброс — как два независимых. Разница в ощущении большая.
  if (подряд) {
    const старт = Math.round((от + до) / 2) - Math.floor(список.length / 2);
    список.forEach((ch, i) => {
      const col = старт + i;
      const пов = поверхность(h, col);
      if (пов < РЯДОВ) положить(h, col, пов - 1, ch);
    });
    return;
  }

  const шаг = (до - от + 1) / (список.length + 1);
  список.forEach((ch, i) => {
    const col = Math.round(от + шаг * (i + 1));
    const пов = поверхность(h, col);
    if (пов < РЯДОВ) положить(h, col, пов - 1, ch);
  });
}

/**
 * Разложить монетки по всей карте до нужного числа.
 *
 * Часть монет уже лежит — над пружинами, на падающих платформах. Остальные
 * раскладываем по опорам равномерно: сначала по одной на каждую подходящую
 * колонку с шагом, потом, если не хватило, вторым проходом повыше.
 */
function разложитьМонеты(h, сколько) {
  let есть = 0;
  for (const c of h.колонки) for (const ch of c) if (ch === 'o') есть++;
  let надо = сколько - есть;
  if (надо <= 0) return;

  // Колонки, куда монетку вообще можно положить: над твёрдой поверхностью и
  // не там, где стоит что-то ещё.
  const годные = [];
  for (let col = 0; col < h.колонки.length; col++) {
    const пов = поверхность(h, col);
    if (пов === РЯДОВ || пов < 2) continue;
    годные.push(col);
  }
  if (!годные.length) return;

  for (const высь of [2, 3, 4]) {
    if (надо <= 0) break;
    const шаг = Math.max(1, Math.floor(годные.length / надо));
    for (let i = 0; i < годные.length && надо > 0; i += шаг) {
      const col = годные[i];
      const пов = поверхность(h, col);
      const c = h.колонки[col];
      const ряд = пов - высь;
      if (ряд < 1 || c[ряд] !== ' ') continue;
      c[ряд] = 'o';
      надо--;
    }
  }
}

/** Сладости — по одной в редких точках, ровно столько, сколько заказано. */
function разложитьСладости(h, сколько) {
  if (сколько <= 0) return;
  const годные = [];
  for (let col = 4; col < h.колонки.length - 4; col++) {
    const пов = поверхность(h, col);
    if (пов === РЯДОВ || пов < 3) continue;
    if (h.колонки[col][пов - 2] !== ' ') continue;
    годные.push(col);
  }
  const шаг = Math.max(1, Math.floor(годные.length / (сколько + 1)));
  for (let i = 0; i < сколько; i++) {
    const col = годные[Math.min(годные.length - 1, шаг * (i + 1))];
    if (col == null) break;
    h.колонки[col][поверхность(h, col) - 2] = '*';
  }
}

// ── Проверка проходимости ──────────────────────────────────────────────────

/**
 * Пройти по карте слева направо и убедиться, что каждый разрыв берётся
 * прыжком. Возвращает список претензий — пустой, если этап проходим.
 *
 * Считаем по краям опор: от последней твёрдой колонки перед пустотой до
 * первой твёрдой после неё. Сколько пикселей можно перелететь при таком
 * перепаде, берём из замеров ПРЫЖОК.
 */
export function проверитьПроходимость(карта) {
  const cols = карта[0].length;
  // Опора — это всё, от чего можно оттолкнуться дальше: земля, площадка,
  // склон, падающая и движущаяся платформы, облачко, пружина. Облачко и
  // пружина не держат вес, но прыжок продолжают, а проверяем мы именно
  // возможность продолжить путь.
  const ОПОРЫ = new Set(['#', '=', '/', '\\', 'x', '-', '|', 'c', 's']);
  const твёрдо = (col) => {
    for (let r = 0; r < карта.length; r++) {
      if (ОПОРЫ.has(карта[r][col])) return r;
    }
    return null;
  };

  const претензии = [];
  let край = null; // последняя опора перед разрывом
  for (let col = 0; col < cols; col++) {
    const r = твёрдо(col);
    if (r == null) continue;
    if (край != null && col - край.col > 1) {
      const пусто = col - край.col - 1;
      const dy = край.row - r; // > 0 — приземляемся выше
      const предел = ПРЫЖОК.вбок[Math.min(2, Math.max(-1, dy))] ?? ПРЫЖОК.вбок[2];
      if (пусто * КЛЕТКА > предел) {
        претензии.push({ col: край.col, пусто, dy, предел });
      }
    }
    край = { col, row: r };
  }
  return претензии;
}

// ── Сборка ─────────────────────────────────────────────────────────────────

/** Построить один участок по его описанию. */
function участок(h, у) {
  switch (у.вид) {
    case 'равнина':
      return равнина(h, у.клеток ?? 6);
    case 'пропасть':
      return пропасть(h, у.ширина ?? 2, у.подъём ?? 0);
    case 'островок':
      return островок(h, у.ширина ?? 2, у.подъём ?? 0);
    case 'горка':
      return горка(h, у);
    case 'пещера':
      return пещера(h, у);
    case 'гора':
      return гораСПружиной(h, у);
    case 'пружина':
      return пружинаСМонетами(h, у);
    case 'ступень':
      // Спуск на клетку без пропасти: нужен, чтобы вернуть дорогу вниз после
      // подъёма, не тратя на это ещё один прыжок.
      h.пол += у.вниз ?? 1;
      return равнина(h, у.клеток ?? 4);
    case 'сплошная': {
      const { диапазон, опоры } = сплошная(h, у.звенья ?? []);
      // Монетка на каждой опоре, если так заказано.
      for (const о of опоры) {
        if (!о.монета && !у.монетаНаОпоре) continue;
        const ряд = рядСимвола(h, о.от);
        if (ряд > 1) положить(h, о.от, ряд - 2, 'o');
      }
      return диапазон;
    }
    default:
      throw new Error(`Неизвестный участок: ${у.вид}`);
  }
}

/** Минимальный промежуток между участками, клеток. */
const ПРОМЕЖУТОК = 3;

/**
 * Выложить этап при заданных промежутках между участками.
 *
 * Вынесено отдельно, потому что сборка идёт дважды: первый раз с
 * минимальными промежутками — чтобы узнать, сколько места занимает
 * содержимое, — второй раз с раздвинутыми, чтобы этап вышел заказанной длины.
 */
function выложить(spec, промежутки) {
  const h = холст();

  // Старт: ровная площадка, чтобы игрок успел понять, где он.
  равнина(h, 6);
  положить(h, 1, h.пол - 1, 'P');

  (spec.участки ?? []).forEach((у, i) => {
    // Промежуток перед участком: препятствия не должны идти вплотную друг к
    // другу — игроку нужно время увидеть следующее, а не отбиваться от двух
    // сразу.
    const запас = у.вплотную ? 0 : промежутки[i];
    if (запас > 0) равнина(h, запас);

    const диапазон = участок(h, у);
    расставитьМонстров(h, диапазон, у.монстры);
    расставитьПрепятствия(h, диапазон, у.препятствия, у.подряд);
    if (у.сердечко) положить(h, диапазон[0] + 1, h.пол - 3, 'h');
  });

  // Финиш: ровная площадка и флаг на ней.
  равнина(h, 6);
  положить(h, h.колонки.length - 4, h.пол - 1, 'F');
  return h;
}

/**
 * Собрать этап по описанию.
 *
 * @param {object} spec описание этапа: seed, длина, монет, сладостей, участки
 * @returns {string[]} карта строками, как рисованная руками
 */
export function generateStage(spec) {
  const rnd = случай(spec.seed ?? 1);
  const n = (spec.участки ?? []).length;

  // Первый проход — вплотную, только чтобы измерить содержимое.
  const пробный = выложить(spec, new Array(n).fill(ПРОМЕЖУТОК));

  // Второй — раздвигаем промежутки так, чтобы вышла заказанная длина. Если
  // содержимое уже длиннее заказа, этап просто получится длиннее: ужимать
  // препятствия ради круглого числа хуже, чем добавить дороги.
  const цель = Math.round(ДЛИНА * (spec.длина ?? 1));
  const промежутки = new Array(n).fill(ПРОМЕЖУТОК);
  let добавка = Math.max(0, цель - пробный.колонки.length);
  while (добавка > 0 && n > 0) {
    промежутки[Math.floor(rnd() * n)] += 1;
    добавка--;
  }

  const h = выложить(spec, промежутки);

  разложитьМонеты(h, spec.монет ?? 0);
  разложитьСладости(h, spec.сладостей ?? 0);

  // Колонки в строки.
  const карта = [];
  for (let r = 0; r < РЯДОВ; r++) {
    карта.push(h.колонки.map((c) => c[r]).join(''));
  }
  return карта;
}
