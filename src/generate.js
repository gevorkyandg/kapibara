/**
 * Сборка этапа по описанию, а не по нарисованной руками карте.
 *
 * Зачем: маршрутов будет много, и рисовать каждый этап в символах дольше, чем
 * описать словами — «сначала подъём по островкам над пропастью, потом равнина
 * с редкими провалами». Из описания получается карта того же вида, что и
 * рисованная: те же символы, тот же сборщик, те же проверки.
 *
 * Два правила, на которых всё держится.
 *
 * 1. **Карта обязана получаться одинаковой каждый раз.** Монеты считаются
 *    отдельным проходом (countCoins), и если бы генератор бросал кости заново,
 *    рейтинг за этап расходился бы с тем, что на карте лежит. Поэтому весь
 *    случай идёт через seed этапа.
 *
 * 2. **Проходимость обеспечивается починкой, а не удачей.** Сначала рельеф
 *    строится как попало, потом отдельный проход проверяет каждый переход
 *    между опорами и правит непосильные: слишком далеко — удлиняем предыдущую
 *    площадку, слишком высоко — опускаем следующую. Без этого любая правка
 *    генератора перетасовывает карту, и проходимость выпадает заново, как в
 *    лотерее.
 *
 * Числа проходимости проверены замерами в игре: прыжок поднимает на 183 px
 * (3 клетки) и переносит через 3 пустые клетки.
 */

import { CHUNK_W } from './levels.js';

/** Максимальный подъём между соседними опорами, клеток. */
const ПОДЪЁМ = 2;

/**
 * Толщина земляного пласта и потолка. Заливать до самого низа карты нельзя:
 * на высоком этапе это тысячи лишних неподвижных тел, а видно всё равно
 * только полэкрана под ногами.
 */
const ПЛАСТ = 7;
const ПОТОЛОК = 3;

/**
 * Сколько клеток между краями опор можно перелететь при таком перепаде.
 * dy > 0 — следующая опора выше.
 */
function дальность(dy, hard) {
  if (dy >= 2) return 3;
  if (dy === 1) return 4;
  return hard ? 5 : 4; // вниз и вровень лететь легче
}

/** Генератор случайных чисел с зерном: одинаковый seed — одна и та же карта. */
function случай(seed) {
  let s = (seed * 2654435761) >>> 0 || 1;
  return () => {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5;
    s >>>= 0;
    return s / 4294967296;
  };
}

const цел = (rnd, a, b) => a + Math.floor(rnd() * (b - a + 1));
const выбор = (rnd, список) => список[Math.floor(rnd() * список.length)];

/**
 * Описание участка:
 *   kind   'flat' | 'up' | 'down'  — куда идёт дорога
 *   style  'ground' | 'islands'    — сплошная земля или острова над пропастью
 *   len    длина в клетках
 *   pits   насколько часто в земле бывают провалы (0..1)
 *   cave   накрыть потолком и повесить шипы
 *   hard   разрешить разрыв на клетку шире (нужен двойной прыжок)
 */
export function generateStage(spec) {
  const rnd = случай(spec.seed ?? 1);
  const rows = spec.rows;
  const вРамках = (r) => Math.max(5, Math.min(rows - 3, r));

  const колонки = []; // { row, solid, ceiling } либо пусто — там пропасть
  const участки = []; // где какой участок начался и кончился
  const пометкиГребня = []; // где стоят метки валунов, поставленные горками

  let ряд = вРамках(spec.startRow);
  let col = 0;

  const земля = (r, ceiling = null) => (колонки[col++] = { row: r, solid: true, ceiling });
  const остров = (r) => (колонки[col++] = { row: r, solid: false, ceiling: null });
  const рампа = (r, куда) => (колонки[col++] = { row: r, solid: true, ceiling: null, ramp: куда });
  const пусто = () => (колонки[col++] = null);

  // ── Стартовая площадка ──────────────────────────────────────────────────
  for (let i = 0; i < 4; i++) земля(ряд);

  // ── Рельеф ──────────────────────────────────────────────────────────────
  for (const уч of spec.sections) {
    const от = col;
    const конец = col + уч.len;
    const шаг = уч.kind === 'up' ? -1 : уч.kind === 'down' ? 1 : 0;

    // Площадка на входе: без неё островок на границе участка обрезался бы по
    // длине участка и превращался в огрызок между двумя разрывами.
    for (let i = 0; i < 3; i++) (уч.style === 'islands' ? остров : земля)(ряд);

    while (col < конец) {
      if (уч.style === 'islands') {
        const ширина = цел(rnd, 2, 4);
        for (let i = 0; i < ширина && col < конец; i++) остров(ряд);

        const подъёмШаг = шаг ? цел(rnd, 1, ПОДЪЁМ) : 0;
        const макс = дальность(шаг < 0 ? подъёмШаг : -1, уч.hard) - 1;
        const разрыв = цел(rnd, 2, Math.max(2, макс));
        if (col + разрыв + 3 > конец) break; // до конца участка не долететь
        for (let i = 0; i < разрыв; i++) пусто();
        ряд = вРамках(ряд + шаг * подъёмШаг);
      } else if (уч.boulders && rnd() < уч.boulders && col + 20 < конец) {
        // Горка под валун — такая же, как на первом этапе: рампы вверх,
        // площадка на гребне, рампы вниз. Без склона валун скучен: катиться
        // ему неоткуда, и он просто выезжает из-за края экрана по ровному.
        const высота = цел(rnd, 3, 4);

        for (let i = 0; i < высота; i++) {
          рампа(ряд, 'up');
          ряд = вРамках(ряд - 1);
        }
        ряд = вРамках(ряд + 1); // последняя рампа уже на уровне гребня
        for (let i = 0; i < 3; i++) земля(ряд);

        // Метка ставится на гребне: место появления камня всё равно ищется от
        // игрока, а метка лишь говорит «здесь бывают валуны».
        пометкиГребня.push({ c: col - 2, r: ряд - 1 });

        for (let i = 0; i < высота - 1; i++) {
          рампа(ряд, 'down');
          ряд = вРамках(ряд + 1);
        }
        for (let i = 0; i < 4; i++) земля(ряд);
      } else {
        const кусок = цел(rnd, 4, 9);
        for (let i = 0; i < кусок && col < конец; i++) {
          земля(ряд, уч.cave ? Math.max(1, ряд - цел(rnd, 6, 7)) : null);
          if (шаг && rnd() < 0.42) ряд = вРамках(ряд + шаг);
        }
        if (rnd() < (уч.pits ?? 0.35)) {
          const провал = цел(rnd, 2, 3);
          if (col + провал + 3 > конец) break;
          for (let i = 0; i < провал; i++) пусто();
        }
      }
    }

    // Площадка на выходе.
    for (let i = 0; i < 3; i++) (уч.style === 'islands' ? остров : земля)(ряд);
    участки.push({ от, до: col - 1, уч });
  }

  // ── Финиш ───────────────────────────────────────────────────────────────
  const финишОт = col;
  for (let i = 0; i < 4; i++) земля(ряд);
  while (col % CHUNK_W !== 0) земля(ряд);

  починить(колонки, участки, rows);

  // ── Начинка ─────────────────────────────────────────────────────────────
  const пометки = [];
  const пометить = (c, r, ch) => пометки.push({ c, r, ch });
  пометить(1, колонки[1].row - 1, 'P');
  пометить(финишОт + 1, колонки[финишОт + 1].row - 1, 'F');
  for (const у of участки) расставить(у, rnd, колонки, пометить, spec);
  for (const м of пометкиГребня) пометить(м.c, м.r, 'B');

  return нарисовать(колонки, пометки, rows, col);
}

/** Список опор: от какого столбца до какого и на какой высоте. */
function площадки(колонки) {
  const список = [];
  for (let c = 0; c < колонки.length; c++) {
    const к = колонки[c];
    if (!к) continue;
    const прошлая = список[список.length - 1];
    if (прошлая && прошлая.до === c - 1 && прошлая.row === к.row) прошлая.до = c;
    else список.push({ от: c, до: c, row: к.row, solid: к.solid });
  }
  return список;
}

/**
 * Проверить каждый переход и починить непосильные.
 *
 * Идём слева направо: починка сдвигает опору и меняет следующий переход,
 * поэтому правим по очереди, а не разом.
 */
function починить(колонки, участки, rows) {
  // Сначала расширяем площадки в одну клетку: приземлиться на такую и тут же
  // прыгнуть дальше почти невозможно, а генератор их плодит на лесенках.
  for (const пл of площадки(колонки)) {
    if (пл.до > пл.от) continue;
    const слева = колонки[пл.от - 1];
    if (слева && !слева.ramp) слева.row = пл.row;
  }

  const список = площадки(колонки);

  // Широкий разрыв разрешён только внутри участка, помеченного hard. Раньше
  // флаг брался «есть ли hard хоть где-нибудь на этапе», и один сложный
  // участок незаметно ослаблял требования ко всему остальному.
  const сложныйВ = (c) => {
    const у = участки.find((z) => c >= z.от && c <= z.до);
    return !!(у && у.уч.hard);
  };

  for (let i = 1; i < список.length; i++) {
    const пред = список[i - 1];
    const тек = список[i];

    // Слишком высоко — опускаем всю площадку до посильного подъёма.
    let dy = пред.row - тек.row;
    if (dy > ПОДЪЁМ) {
      // Опускать можно только до нижнего края карты. Уехавшая за край колонка
      // не рисуется вовсе, но в списке опор остаётся — и соседние площадки
      // переставали быть соседними, а значит, разрыв между ними никто не
      // чинил. Так на карте появлялись перелёты в шесть клеток.
      const сдвиг = Math.min(dy - ПОДЪЁМ, rows - 3 - тек.row);
      for (let c = тек.от; c <= тек.до; c++) {
        колонки[c].row += сдвиг;
        if (колонки[c].ceiling != null) колонки[c].ceiling += сдвиг;
      }
      тек.row += сдвиг;
      dy = пред.row - тек.row;
    }

    // Слишком далеко — удлиняем предыдущую площадку навстречу.
    let dx = тек.от - пред.до;
    const предел = дальность(dy, сложныйВ(тек.от));
    while (dx > предел && пред.до + 1 < тек.от) {
      пред.до += 1;
      колонки[пред.до] = { row: пред.row, solid: пред.solid, ceiling: null };
      dx -= 1;
    }
  }
}

/** Разложить по участку монстров, валуны, шипы, монеты и сладости. */
function расставить(у, rnd, колонки, пометить, spec) {
  const { от, до, уч } = у;
  const пул = spec.monsters || ['m', 'f', 'l'];
  const летуны = пул.filter((k) => 'fbw'.includes(k));
  const свои = площадки(колонки).filter((пл) => пл.от >= от && пл.до <= до);

  for (const пл of свои) {
    const ширина = пл.до - пл.от + 1;
    const центр = пл.от + Math.floor(ширина / 2);

    if (rnd() < 0.7) пометить(центр, пл.row - 2, 'o');

    // Сердечко — редкая находка: на сложных маршрутах оно и есть та
    // соломинка, ради которой стоит свернуть с дороги.
    if (уч.hearts && ширина >= 3 && rnd() < уч.hearts) пометить(пл.от + 1, пл.row - 2, 'h');

    // Монстры — только там, где им есть где ходить, и где игроку есть куда
    // отступить: четыре клетки, а не три.
    //
    // На островке над пропастью держим только тех, кого можно перепрыгнуть.
    // Ёжик на трёхклеточном острове — не сложность, а ловушка: прыгать на
    // него нельзя, разойтись негде, и игрок гибнет раз за разом, возвращаясь
    // на ту же точку.
    if (ширина >= 4 && rnd() < (уч.monsters ?? 0.5)) {
      const годные = пл.solid ? пул : пул.filter((k) => !'edz'.includes(k));
      if (годные.length) пометить(центр, пл.row - 1, выбор(rnd, годные));
    }

  }

  // Валуны катятся по сплошной земле — но искать под них ровную площадку
  // нельзя: дорога поднимается и опускается почти каждую вторую клетку, и
  // ровных шестёрок на одной высоте на ней почти не бывает. Поэтому берём
  // непрерывный кусок земли, не глядя на перепад: камню ступеньки не помеха.
  if (уч.boulders) {
    let c = от;
    while (c <= до) {
      if (!колонки[c] || !колонки[c].solid) {
        c++;
        continue;
      }
      let длина = 0;
      while (колонки[c + длина] && колонки[c + длина].solid && c + длина <= до) длина++;
      // Куски земли редкие, но длинные — по три десятка клеток. Один забег на
      // кусок означал бы один валун на весь этап, поэтому идём внутри куска с
      // шагом и бросаем кости на каждом.
      // Отступ от краёв куска: валун, срывающийся сразу за посадкой с широкого
      // разрыва, отступать не даёт — сзади пропасть, и игрок гибнет по кругу.
      for (let место = c + 6; место + 5 < c + длина; место += цел(rnd, 9, 14)) {
        if (rnd() >= уч.boulders) continue;
        const сколько = цел(rnd, 1, уч.bouldersMax ?? 2);
        for (let i = 0; i < сколько; i++) {
          const кол = место + i;
          if (колонки[кол]) пометить(кол, колонки[кол].row - 1, 'B');
        }
      }
      c += длина;
    }
  }

  // Над пропастями: монета повыше (так в ТЗ), иногда сладость, иногда
  // движущаяся платформа. Платформу вешаем выше головы — на клетке над землёй
  // она, отъехав на твёрдый участок, встаёт стеной поперёк дороги.
  for (let c = от; c <= до; c++) {
    if (колонки[c] || !колонки[c - 1]) continue; // считаем по левому краю
    let ширина = 0;
    while (!колонки[c + ширина] && c + ширина <= до) ширина++;
    const слева = колонки[c - 1];
    const центр = c + Math.floor(ширина / 2);
    пометить(центр, слева.row - 3, 'o');
    if (rnd() < 0.2) пометить(центр, слева.row - 4, '*');
    if (ширина >= 3 && rnd() < 0.3) пометить(центр, слева.row - 2, '-');
    if (летуны.length && rnd() < (уч.flyers ?? 0.3)) {
      // Высоту берём в просвете между полом и потолком. Пять-семь клеток над
      // уступом — это ровно там, где в пещере проходит потолок: муха
      // оказывалась прижатой к нему, размах качания схлопывался в ноль, и она
      // просто висела на месте.
      const потолок = слева.ceiling ?? -1;
      const низ = слева.row - 2;
      const верх = Math.max(2, потолок + 2);
      пометить(центр, Math.max(верх, Math.min(низ, слева.row - цел(rnd, 3, 6))), выбор(rnd, летуны));
    }
  }

  // Падающие шипы — только под потолком пещеры.
  if (уч.cave) {
    for (let c = от; c <= до; c++) {
      const к = колонки[c];
      if (!к || к.ceiling == null) continue;
      if (rnd() > (уч.spikes ?? 0.12)) continue;
      пометить(c, к.ceiling + 1, rnd() < (уч.aimedSpikes ?? 0.3) ? 'V' : 'v');
    }
  }
}

/** Превратить описание колонок в ряды символов. */
function нарисовать(колонки, пометки, rows, ширина) {
  const сетка = [];
  for (let r = 0; r < rows; r++) сетка.push(new Array(ширина).fill(' '));

  for (let c = 0; c < ширина; c++) {
    const к = колонки[c];
    if (!к || к.row < 0 || к.row >= rows) continue;
    if (к.ramp) {
      сетка[к.row][c] = к.ramp === 'up' ? '/' : '\\';
      for (let r = к.row + 1; r < Math.min(rows, к.row + ПЛАСТ); r++) сетка[r][c] = '#';
    } else if (к.solid) {
      for (let r = к.row; r < Math.min(rows, к.row + ПЛАСТ); r++) сетка[r][c] = '#';
    } else {
      сетка[к.row][c] = '#';
    }
    if (к.ceiling != null) {
      for (let r = Math.max(0, к.ceiling - ПОТОЛОК); r <= к.ceiling && r < rows; r++) {
        сетка[r][c] = '#';
      }
    }
  }

  for (const п of пометки) {
    if (п.c < 0 || п.c >= ширина || п.r < 0 || п.r >= rows) continue;
    if (сетка[п.r][п.c] !== ' ') continue; // землю не затираем
    сетка[п.r][п.c] = п.ch;
  }

  return сетка.map((r) => r.join(''));
}
